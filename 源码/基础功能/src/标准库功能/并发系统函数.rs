// ============================================================
//  编译模式并发：原生任务句柄桥接
//  编译器经 CALL 160-163 调用本组助手；与解释器 VM 线程模型互不干扰。
// ============================================================

/// 任务入口标准签名（sret-free）：输出指针 + 参数数组指针 + 数量。
/// 编译器为每个"作为任务目标"的函数生成一个此签名的 thunk（负责调用任务体并打包结果为 拥有值）。
type 任务入口 = extern "C" fn(*mut crate::公共服务::拥有值, *const 运行时值, i64);

/// 任务启动：在独立 OS 线程执行任务入口（thunk 包裹参数数组），注册句柄并返回 id。
/// 编译模式经 CALL 160 调用本函数；与解释器 VM 线程模型互不干扰，共用同一份并发运行时。
pub(crate) fn 并发启动任务(函数指针: i64, 参数: &[运行时值]) -> u64 {
    let 入口: 任务入口 = unsafe { std::mem::transmute(函数指针 as usize) };
    let 参数克隆: Vec<运行时值> = 参数.to_vec();
    // 🔁 2026-09-24（**D1：任务在途值记账 —— 接收方自持 +1 / 结束 −1**）★
    //   编译模式把**调用方句柄**（`to_vec()` 浅拷贝）交给**异步线程**，任务体**之后**才读取它们 ⇒
    //   ① **任务侧必须自持一份引用（+1）**：否则调用方一旦释放（前端在调用点释放自有右值临时，
    //      或槽被覆盖）⇒ 任务读取到**已回收对象** ⇒ **use-after-free** ✗
    //      （这正是"前端调用点释放闭包临时"在编译模式曾致 **TIMEOUT** 的根因 ✓，而解释模式
    //       因 `执行任务启动寄存器` 在**调用线程**已深提取捕获 ⇒ 调用点释放本就安全 ✓）
    //   ② 任务运行结束（读取完毕、帧消亡）后由**任务侧 −1**，与 `+1` 成对 ⇒ **两模式各自平衡** ✓
    //   ⚠ 仅在 `标签_句柄` 且非 0 时计数（`堆增加引用`/`堆释放` 对陈旧/零句柄本就幂等 ✓）
    let 任务自持句柄: Vec<u64> = 参数克隆
        .iter()
        .filter(|v| v.标签 == 标签_句柄 && v.句柄 != 0)
        .map(|v| v.句柄)
        .collect();
    for 句柄 in &任务自持句柄 {
        堆增加引用(*句柄);
    }
    let 句柄 = crate::公共服务::任务句柄::启动(move || {
        let mut 结果槽 = crate::公共服务::拥有值::空值;
        入口(&mut 结果槽, 参数克隆.as_ptr(), 参数克隆.len() as i64);
        // 🔁 D1：任务侧读取完毕 ⇒ 释放自持引用（与上方 `+1` 成对；结果已经由 thunk
        //   深提取为 `拥有值`（不含堆句柄）⇒ 此处 −1 不影响结果 ✓）
        for 句柄 in &任务自持句柄 {
            堆释放(*句柄);
        }
        结果槽
    });
    crate::公共服务::创建任务句柄(句柄)
}

/// 任务等待：按 id 取句柄，阻塞等待结果并转为 运行时值。
pub(crate) fn 并发等待任务(句柄id: u64) -> 运行时值 {
    let 句柄 = crate::公共服务::取任务(句柄id);
    match 句柄 {
        Some(h) => {
            let 结果 = h.等待结果();
            拥有值转运行时值(&结果)
        }
        None => 运行时值::空值(),
    }
}

/// 批量等待：按 id 列表取句柄，按序等待，返回结果数组句柄。
pub(crate) fn 并发批量等待(句柄id列表: &[u64]) -> 运行时值 {
    let 句柄列表: Vec<crate::公共服务::任务句柄> =
        句柄id列表.iter().filter_map(|id| crate::公共服务::取任务(*id)).collect();
    let 结果们 = crate::公共服务::任务句柄::批量等待(&句柄列表);
    let 值列表: Vec<运行时值> = 结果们.iter().map(拥有值转运行时值).collect();
    分配数组(值列表)
}

/// 批量等待超时：超时未完成的任务填空值，已完成的仍可经 任务等待 取结果。
pub(crate) fn 并发批量等待超时(句柄id列表: &[u64], 超时毫秒: u64) -> 运行时值 {
    let 句柄列表: Vec<crate::公共服务::任务句柄> =
        句柄id列表.iter().filter_map(|id| crate::公共服务::取任务(*id)).collect();
    let 结果们 = crate::公共服务::任务句柄::批量等待超时(&句柄列表, 超时毫秒);
    let 值列表: Vec<运行时值> = 结果们.iter().map(拥有值转运行时值).collect();
    分配数组(值列表)
}
