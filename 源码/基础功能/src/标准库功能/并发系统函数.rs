#[derive(Debug, Clone)]
pub(crate) enum 监听选项 {
    通道可读(String, u64),
    超时事件(String, u64),
    终止信号(String, u64),
}

// 监听选项缓存按线程隔离（一个任务 = 一个线程，注册与 多路监听 总在同一线程）。
// 旧实现是进程级 Mutex<Vec>：多路监听 阻塞期间一直持锁，其他任务连注册选项都会卡住（死锁），
// 并且会吞掉别的任务注册的选项（串台）。
thread_local! {
    pub(crate) static 线程监听缓存: std::cell::RefCell<Vec<监听选项>> = const { std::cell::RefCell::new(Vec::new()) };
}

// 这些函数封装对 crate::公共服务 全局句柄表的访问
