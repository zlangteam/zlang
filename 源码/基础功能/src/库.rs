use std::alloc::{alloc, Layout};

/// 运行时内存分配
#[export_name = "智语言分配内存"]
pub extern "C" fn 智语言分配内存(大小: i64) -> i64 {
    if 大小 <= 0 { return 0; }
    let 布局 = match Layout::from_size_align(大小 as usize, 8) {
        Ok(布局) => 布局,
        Err(_) => return 0,
    };
    unsafe {
        let 指针 = alloc(布局);
        if 指针.is_null() { 0 } else { 指针 as i64 }
    }
}

/// 运行时输出
#[export_name = "智语言输出"]
pub extern "C" fn 智语言输出(文本: *const u8, 长度: i64) {
    #[cfg(not(windows))]
    {
        use std::io::Write;
        if 文本.is_null() || 长度 < 0 { return; }
        let 字节 = unsafe { std::slice::from_raw_parts(文本, 长度 as usize) };
        let mut 标准输出 = std::io::stdout().lock();
        let _ = 标准输出.write_all(字节);
        let _ = 标准输出.write_all(b"\n");
        let _ = 标准输出.flush();
    }
    #[cfg(windows)]
    unsafe {
        let 句柄 = GetStdHandle(STD_OUTPUT_HANDLE);
        let mut 已写入: u32 = 0;
        WriteFile(句柄, 文本, 长度 as u32, &mut 已写入, 0 as *const u8);
        let 换行: [u8; 2] = [0x0D, 0x0A];
        WriteFile(句柄, 换行.as_ptr(), 2, &mut 已写入, 0 as *const u8);
    }
}

