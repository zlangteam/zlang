/// 编译模式系统调用入口 (C ABI)。
/// 索引: CALL 分发器编号 (1-199)
/// 参数: 指向 运行时值 数组的指针
/// 参数数量: 数组长度
/// 输出: 指向调用方预分配 运行时值（32字节）的指针（写入结果）
///
/// 解释模式不走此 C ABI，而是直接调 base::系统调用()
#[export_name = "智语言_系统调用"]
pub extern "C" fn 智语言系统调用(索引: u64, 参数: *const 值类型::运行时值, 参数数量: u64, 输出: *mut 值类型::运行时值) {
    let 结果 = if 参数.is_null() || 参数数量 == 0 {
        系统调用(索引 as usize, &[])
    } else {
        unsafe {
            let 切片 = std::slice::from_raw_parts(参数, 参数数量 as usize);
            系统调用(索引 as usize, 切片)
        }
    };
    if !输出.is_null() {
        unsafe { std::ptr::write(输出, 结果); }
    }
}

/// 编译模式任务 thunk 结果打包：将 (标签,载荷) 写入 拥有值 输出指针。
/// 由编译器生成的任务 thunk 调用，避免脆弱的 sret ABI（显式 out-pointer）。
///
/// ⚡双模式⚡ 彻底修复：此前 `_ => 空值` 会静默吞掉结构体（标签_句柄）等复合类型，
/// 与 HTTP thunk 误用本函数导致 500 属同一类缺陷。现改为经 `重建运行时值` 重建完整
/// 运行时值，再经 `运行时值转拥有值` 深转换（文本/数组/映射/结构体/闭包/异常全覆盖），
/// 使任务即便未来返回结构体也不会静默丢失（与 `智语言_打包运行时值` 对称地做到“零静默丢弃”）。
/// 当前任务仅返回基本类型，新增分支为前向保护，对基本类型行为完全不变。
#[export_name = "智语言_打包结果"]
#[allow(improper_ctypes_definitions)]
pub extern "C" fn 智语言打包结果(标签: u64, 载荷: i64, 输出: *mut crate::公共服务::拥有值) {
    let 运行时值 = 堆操作::重建运行时值(标签, 载荷);
    let 拥有值 = 分发器::运行时值转拥有值(&运行时值);
    unsafe { std::ptr::write(输出, 拥有值); }
}

/// ⚡双模式⚡: 编译模式用户函数结果打包：将 (标签,载荷) 重建为完整 运行时值
/// 写入 `*mut 运行时值` 输出指针。与 `智语言_打包结果` 不同，此处通过 `重建运行时值`
/// 正确处理结构体（标签_句柄 → 句柄字段）。
/// 由编译器生成的 回调桥/任务 thunk 调用（任务执行器.rs 生成回调桥 / 生成任务thunk）。
/// 2026-08-19 阶段二：HTTP 专用 thunk 已删除，HTTP 处理器改走 回调桥。
#[export_name = "智语言_打包运行时值"]
#[allow(improper_ctypes_definitions)]
pub extern "C" fn 智语言打包运行时值(标签: u64, 载荷: i64, 输出: *mut 值类型::运行时值) {
    unsafe { std::ptr::write(输出, 堆操作::重建运行时值(标签, 载荷)); }
}

/// 编译器简化系统调用入口：所有参数作为 i64 整数传递，输出为 (tag, int) 对。
/// 最多支持 4 个参数，覆盖大部分系统调用（数学、文件、时间、系统、工具等）。
#[export_name = "智语言_系统调用简"]
pub extern "C" fn 智语言系统调用简(
    索引: u64, argc: u64,
    p0: i64, p1: i64, p2: i64, p3: i64,
    out_tag: *mut u64, out_int: *mut i64,
) {
    let mut 运行时参数: Vec<值类型::运行时值> = Vec::with_capacity(argc as usize);
    let 参数列表 = [p0, p1, p2, p3];
    for i in 0..argc.min(4) {
        运行时参数.push(值类型::运行时值::整数(参数列表[i as usize]));
    }
    let 结果 = 系统调用(索引 as usize, &运行时参数);
    if !out_tag.is_null() { unsafe { *out_tag = 结果.标签; } }
    if !out_int.is_null() { unsafe { *out_int = 结果.整数; } }
}

/// 编译模式堆操作统一入口 (C ABI)。
/// 操作码: 堆操作索引（见 堆操作.rs 的 堆_* 常量）
/// argc:   操作数个数（最多 4）
/// 标签数组: 指向 argc 个 u64 标签的指针（每个操作数的类型标签）
/// 值数组:   指向 argc 个 i64 载荷的指针（每个操作数的数据；句柄即句柄 id，小数即位模式）
/// 输出:     指向调用方预分配 运行时值（32字节）的指针（写入主结果）
/// 输出2:    可选第二输出（仅 数组取末尾 用于写回弹出的元素），为空则忽略
///
/// 解释模式不走此 C ABI，而是直接调 base::堆操作::堆操作()
/// 类型安全的二元算术入口：用大魔数标志位绕过 Cranelift 小整数常量损坏 bug。
/// 左类型标志: 77=整数, 78=小数。载荷始终以原始 i64（整数=值本身，小数=f64::to_bits）。
#[export_name = "智语言_二元算术"]
pub extern "C" fn 智语言二元算术(
    操作码: u64,
    左类型标志: u64,
    左载荷: i64,
    右类型标志: u64,
    右载荷: i64,
    输出: *mut 值类型::运行时值,
) {
    let 左 = match 左类型标志 {
        值类型::类型标志_整数 => 值类型::运行时值::整数(左载荷),
        值类型::类型标志_小数 => 值类型::运行时值::小数(f64::from_bits(左载荷 as u64)),
        _ => 值类型::运行时值::空值(),
    };
    let 右 = match 右类型标志 {
        值类型::类型标志_整数 => 值类型::运行时值::整数(右载荷),
        值类型::类型标志_小数 => 值类型::运行时值::小数(f64::from_bits(右载荷 as u64)),
        _ => 值类型::运行时值::空值(),
    };
    let 参数 = vec![左, 右];
    let 结果 = 堆操作::堆操作(操作码 as usize, &参数);
    if !输出.is_null() {
        unsafe { std::ptr::write(输出, 结果); }
    }
}

