#[export_name = "智语言_堆操作"]
pub extern "C" fn 智语言堆操作(
    操作码: u64,
    argc: u64,
    标签数组: *const u64,
    值数组: *const i64,
    输出: *mut 值类型::运行时值,
    输出2: *mut 值类型::运行时值,
) {
    let mut 参数: Vec<值类型::运行时值> = Vec::with_capacity(argc as usize);
    if argc > 0 && !标签数组.is_null() && !值数组.is_null() {
        let 标签切片 = unsafe { std::slice::from_raw_parts(标签数组, argc as usize) };
        let 值切片 = unsafe { std::slice::from_raw_parts(值数组, argc as usize) };
        for i in 0..argc as usize {
            参数.push(堆操作::重建运行时值(标签切片[i], 值切片[i]));
        }
    }
    // ⚡双模式⚡: 数组取末尾 必须在 堆_数组取末尾 就地弹出「前」捕获最后元素，
    // 否则弹出后 v.last() 已是新末尾（与解释器 一元寄存器指令 返回弹出前元素 不一致）。
    let 弹出元素 = if 操作码 as usize == 堆操作::堆_数组取末尾 {
        if let Some(参数首) = 参数.first() {
            if let Some(堆) = 值类型::堆读取(参数首.句柄) {
                if let 值类型::堆数据::数组(v) = 堆 {
                    v.last().cloned()
                } else {
                    None
                }
            } else {
                None
            }
        } else {
            None
        }
    } else {
        None
    };
    let 结果 = 堆操作::堆操作(操作码 as usize, &参数);
    if !输出.is_null() {
        // 写出完整 运行时值 结构（32字节）：标签@0, 整数@8, 小数@16, 句柄@24。
        // 与编译器 编译系统调用 读取约定一致，避免返回的句柄/小数丢失。
        unsafe { std::ptr::write(输出, 结果); }
    }
    // 数组取末尾双输出：将被弹出的元素写入 输出2（已弹出前捕获）。
    // ⚠️ 空数组时 弹出元素 = None，必须显式写 空值，否则 输出2 缓冲残留编译期未初始化数据，
    // 导致编译模式 `空数组.取末尾()` 返回垃圾值（解释模式走 输出 主结果=空值 不受影响）。
    if 操作码 as usize == 堆操作::堆_数组取末尾 && !输出2.is_null() {
        let 写回 = 弹出元素.unwrap_or(值类型::运行时值::空值());
        unsafe { std::ptr::write(输出2, 写回); }
    }
}

/// 由字节缓冲区分配一个运行时文本句柄，返回句柄 id（供编译器字符串字面量使用）
#[export_name = "智语言分配文本"]
pub extern "C" fn 智语言分配文本(指针: *const u8, 长度: i64) -> u64 {
    let 字节 = if 指针.is_null() || 长度 <= 0 {
        Vec::new()
    } else {
        unsafe { std::slice::from_raw_parts(指针, 长度 as usize).to_vec() }
    };
    let s = String::from_utf8_lossy(&字节).to_string();
    值类型::分配文本(s).句柄
}

/// 🆕 方案A：由只读静态段（COFF .rdata / 字节码常量池）零拷贝构造文本句柄。
/// 指向进程级常驻只读内存，不分配/不拷贝；仅在被修改时经写时复制升级为 堆数据::文本(String)。
#[export_name = "智语言分配文本自静态"]
pub extern "C" fn 智语言分配文本自静态(指针: *const u8, 长度: i64) -> u64 {
    // 🔁 2026-09-23（阶段 9 双引擎等价性门禁**暴露并修复**）：**空字面量也必须用 `文本_静态`**。
    //   现象：门禁报 `123/124/125` —— 两引擎 `存活` **总数相同**，但 `存活按种类` **差 1**
    //     （解释 `文本_静态`+1 / 编译 `文本`+1）。根因：三者**都有空字面量 `""`**：
    //     · 解释侧（阶段 1d 惰性池）对长度 0 也建立 `文本_静态(地址, 0)` ✓
    //     · 编译侧走本函数，旧判定 `长度 <= 0` ⇒ 分配 `堆数据::文本(String::new())` ✗
    //   ⇒ **同一逻辑对象在两引擎"种类"不同** ⇒ 判据 J1（按种类逐项可比）的前提被破坏。
    //   修法：长度 0 + **非空指针** ⇒ `文本_静态(指针, 0)`（读为空串；被修改时经 COW 升级为 `文本`
    //   ⇒ 语义与"拥有空副本"完全一致 ✓，且省掉一次拥有分配）。
    //   ⚠ 仅当指针为空（无静态段可用，防御路径）才退化为拥有副本 —— 保证空指针安全 ✓
    if 指针.is_null() {
        return 值类型::分配文本(String::new()).句柄;
    }
    let 长度 = if 长度 < 0 { 0 } else { 长度 as usize };
    值类型::堆分配(值类型::堆数据::文本_静态(指针 as usize, 长度))
}

// ════════════════════════════════════════════════════════════════════════════
//  🆕 阶段 1b（2026-09-22）**统一字面量表**
//
//  缺陷（实测，探针 `I_字面量赋值_300`）：编译模式字符串字面量此前在**每个使用点**发射
//    `智语言分配文本自静态` ⇒ 每次执行都新建一个堆对象，且**无任何所有者**
//    （不进槽 ⇒ 不入拥有型槽清单 ⇒ 弹帧不 −1；编译模式也没有解释模式那样的"常量池"可 drain）
//    ⇒ **逐轮泄漏**：300 轮循环内 `结果 = "锚"` ⇒ 编译侧 `文本_静态` 存活 **301**，
//      而解释侧仅 **2**（常量池一份）⇒ 既是内存泄漏，也是**两引擎存活口径差（J1）**的主源。
//
//  修法：**按「LIR 常量池索引」惰性分配 + 去重** —— 同一索引 ⇒ 同一对象（全程序唯一）：
//    ① 同一字面量在循环内反复使用 ⇒ **不再重复分配** ✓
//    ② 由**已有的**编译帧根枚举一并喂入（见 `值类型.rs::枚举编译帧根`）⇒ 字面量是**根**（可达）✓
//    ③ 与解释模式"每个常量索引一份对象"**同构** ⇒ 两引擎 J1 逐项相等 ✓
//
//  ⚠⚠ **为什么不在本表新注册一个根提供者**：`注销根提供者` 的"**终局对账**"触发条件是
//    「本线程仅剩 1 个提供者 且 全局仅此 1 个」⇒ 若常驻一个额外提供者，该条件**永不成立**
//    ⇒ 终局对账不打印（内存门禁将报"产物无对账输出"）✗
//    ⇒ **复用既有根枚举是唯一安全的接入点**。
//
//  ⚠ 锁序铁律：本表的锁**只能在"不持堆锁"时获取**，且持本表锁时可再取堆锁（`堆分配`）
//    ⇒ 全局唯一顺序 **字面量表锁 → 堆锁**；`堆释放`/级联/根枚举均只取其中一把 ⇒ 无环、无死锁 ✓
// ════════════════════════════════════════════════════════════════════════════
static 字面量表: std::sync::LazyLock<std::sync::Mutex<Vec<Option<u64>>>> =
    std::sync::LazyLock::new(|| std::sync::Mutex::new(Vec::new()));

/// 取（或惰性建立）指定 **LIR 常量池索引** 对应的文本字面量句柄（**同一索引 ⇒ 同一对象**）。
/// `索引 < 0`（防御）⇒ 退化为"每次新建"（与旧行为一致，仅丧失去重，不损正确性）。
#[export_name = "智语言_取字面量文本"]
pub extern "C" fn 智语言_取字面量文本(索引: i64, 指针: *const u8, 长度: i64) -> u64 {
    if 索引 < 0 {
        return 智语言分配文本自静态(指针, 长度);
    }
    let i = 索引 as usize;
    // ① 查表（**短锁**：本临界区内**绝不调用任何会取堆锁的函数**）
    {
        let 表 = 字面量表.lock().unwrap();
        if let Some(Some(已有)) = 表.get(i) {
            return *已有;
        }
    }
    // ② **锁外分配**：`堆分配` 在达到阈值时会触发 GC/可达性对账，而对账要**枚举根**
    //    ⇒ 会回调 `枚举字面量表根`（取本表锁）⇒ 若此刻仍持表锁则**同线程重入死锁**
    //    （2026-09-23 实测踩到：`123内存文本槽释放` 编译模式在开对账时**永久挂住**，
    //      并在被杀后**锁定产物** ⇒ 后续编译报 `rust-lld: permission denied`，
    //      表现即"全量门禁莫名卡住"）。
    //    ⚠ 铁律：**任何 Mutex/RwLock 都不得跨"可能取堆锁"的调用持有**。
    let 新 = 智语言分配文本自静态(指针, 长度);
    // ③ 再锁写入（竞争：他人先建 ⇒ 本线程本次分配多余 ⇒ **锁外**释放）
    let 已有 = {
        let mut 表 = 字面量表.lock().unwrap();
        if 表.len() <= i { 表.resize(i + 1, None); }
        let 已有 = 表[i];
        if 已有.is_none() { 表[i] = Some(新); }
        已有
    };
    match 已有 {
        Some(h) => {
            // 锁已释放 ⇒ 可安全取堆锁
            值类型::堆释放(新);
            h
        }
        None => 新,
    }
}

/// 供**已有的**编译帧根枚举调用：把字面量表内所有句柄喂给根回调
/// （字面量 = **程序级常量**，与解释模式常量池同构 ⇒ 使两引擎可达/存活口径逐项可比）。
/// ⚠ 只读本表锁，**绝不取堆锁**（根枚举必须在无堆锁上下文 ⇒ 见 `值类型.rs` 铁律）✓
pub fn 枚举字面量表根(回调: &mut dyn FnMut(u64)) {
    let 表 = 字面量表.lock().unwrap();
    if std::env::var("智语言_调试全局表").is_ok() {
        let 句柄集: Vec<u64> = 表.iter().flatten().copied().collect();
        eprintln!("[字面量表枚举] 项数={} 已物化句柄={:?}", 表.len(), 句柄集);
    }
    for h in 表.iter().flatten() {
        回调(*h);
    }
}

// ════════════════════════════════════════════════════════════════════════════
//  🆕 阶段 3a（2026-09-23）**编译侧「全局变量持久区」纳入根枚举**
//
//  缺口（实测）：同一用例 `可达` —— 解释模式 **34** / 编译模式 **11**（差值 = 只被全局变量引用的对象）。
//    原因：编译模式把模块级全局变量放在产物**静态数据区**（每全局 16B = 标签@+0 / 载荷@+8，索引 = gi+1），
//    而根枚举此前只覆盖"影子帧链 + 字面量表" ⇒ **全局变量不是根**。
//  后果：① J2 口径不可比（两引擎可达数不同）；② 若开启 `智语言_内存兜底清扫`，
//       **只被全局变量引用的对象会被误收**（默认关闭 ⇒ 当前无实害，但属正确性隐患）。
//
//  修法：入口函数 prologue 调 `智语言_注册编译全局表(基址, 槽数)` 注册一次（跨函数同一数据区），
//    根枚举从**已有的**帧根枚举一并喂入（与 1b 字面量表同法 ⇒ 不新增根提供者，避免破坏"终局对账"触发条件）。
//
//  ⚠ 锁纪律（1b 重入死锁的教训）：本表锁**只在无堆锁时**取；枚举时**先取快照、释放锁**，再回调 ✓
//  ⚠ 内存安全：被注册的是**产物数据段**地址（进程存活期内有效）；读用 `read_volatile`（该内存可被
//    被编译代码写入，禁止编译器把读取重排/缓存到注册之前）。
// ════════════════════════════════════════════════════════════════════════════
static 编译全局表: std::sync::LazyLock<std::sync::Mutex<Vec<(usize, usize)>>> =
    std::sync::LazyLock::new(|| std::sync::Mutex::new(Vec::new()));

/// 注册「全局变量持久区」：`基址` = 数据段首地址，`槽数` = 全局数 + 1（索引自 gi+1 起 ⇒ 偏移 0 为保留槽）。
/// 仅入口函数 prologue 调用一次；按 `(基址, 槽数)` **去重**（重复注册幂等）。
#[export_name = "智语言_注册编译全局表"]
pub extern "C" fn 智语言_注册编译全局表(基址: usize, 槽数: usize) {
    if std::env::var("智语言_调试全局表").is_ok() {
        eprintln!("[全局表注册] 基址=0x{:x} 槽数={}", 基址, 槽数);
    }
    if 基址 == 0 || 槽数 == 0 { return; }
    let mut 表 = 编译全局表.lock().unwrap();
    if !表.contains(&(基址, 槽数)) {
        if std::env::var("智语言_调试全局表").is_ok() {
            eprintln!("[全局表注册] 已登记（去重后表项数={}）", 表.len() + 1);
        }
        表.push((基址, 槽数));
    }
}

/// 供**已有的**编译帧根枚举调用：把全局区中**所有持堆句柄的槽**喂给根回调。
/// 过滤规则与两引擎一致：`标签 == 标签_句柄 && 载荷 != 0`。
pub fn 枚举编译全局表根(回调: &mut dyn FnMut(u64)) {
    // ⚠ 先取快照并**释放表锁**，再逐项读取/回调（回调侧不得持锁 ⇒ 见 1b 死锁教训）
    let 快照: Vec<(usize, usize)> = {
        let 表 = 编译全局表.lock().unwrap();
        表.clone()
    };
    let 调试 = std::env::var("智语言_调试全局表").is_ok();
    if 调试 {
        eprintln!("[全局表枚举] 表项数={}", 快照.len());
    }
    for (基址, 槽数) in 快照 {
        for i in 0..槽数 {
            // 每槽 16 字节：(标签 @ +0, 载荷 @ +8)
            unsafe {
                let 标签 = std::ptr::read_volatile((基址 + i * 16) as *const i64);
                let 载荷 = std::ptr::read_volatile((基址 + i * 16 + 8) as *const i64);
                if 调试 {
                    eprintln!("[全局表枚举] 槽{} 标签={} 载荷={}", i, 标签, 载荷);
                }
                if 标签 == 值类型::标签_句柄 as i64 && 载荷 != 0 {
                    回调(载荷 as u64);
                }
            }
        }
    }
}

/// 打印一个运行时文本句柄（供编译器 输出 内置函数使用）
#[export_name = "智语言输出文本"]
pub extern "C" fn 智语言输出文本(句柄: u64) {
    let s = 值类型::运行时值::句柄(句柄).取文本();
    println!("{}", s);
}

/// 获取运行时全局堆中的对象文本（供编译器调试/输出用）
/// 句柄: 堆对象句柄
/// 输出缓冲区: 调用方提供的可写内存
/// 最大长度: 缓冲区大小
/// 返回: 实际写入的字节数
#[export_name = "智语言_读取文本"]
pub extern "C" fn 智语言读取文本(句柄: u64, 输出: *mut u8, 最大长度: u64) -> u64 {
    let s = 值类型::运行时值::句柄(句柄).取文本();
    let 字节 = s.as_bytes();
    let 拷贝数 = 字节.len().min(最大长度 as usize);
    if 拷贝数 > 0 && !输出.is_null() {
        unsafe {
            std::ptr::copy_nonoverlapping(字节.as_ptr(), 输出, 拷贝数);
        }
    }
    拷贝数 as u64
}
