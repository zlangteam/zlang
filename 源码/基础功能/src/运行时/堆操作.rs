/// 容器实际种类（运行时判定，用于「编译期类型未知」的容器方法调用分发）。
#[derive(PartialEq, Eq, Clone, Copy, Debug)]
pub enum 容器种类 { 数组, 映射, 文本, 其它 }

/// 按堆对象实际内容判定容器种类。2026-08-15 统一容器方法分发的基石：
/// 编译期无法确定元素/容器类型时（裸 数组/映射 标注、任意类型、嵌套索引结果、泛型擦除），
/// 前端发射「通用容器方法」操作码，由本函数在运行时按真实堆数据分派到数组/映射语义。
pub fn 判定容器种类(v: &运行时值) -> 容器种类 {
    if v.标签 != 标签_句柄 { return 容器种类::其它; }
    堆读取借用(v.句柄, |数据| match 数据 {
        堆数据::数组(_) => 容器种类::数组,
        堆数据::映射(_) => 容器种类::映射,
        堆数据::文本(_) => 容器种类::文本,
        _ => 容器种类::其它,
    })
    .unwrap_or(容器种类::其它)
}

/// 通用容器方法用在非容器值上时抛可捕获异常（禁静默返回空值，避免缺陷被吞掉）。
fn 抛不支持容器方法(容器: &运行时值, 方法名: &str) {
    let 类型名 = 运行时值取类型名称(容器);
    let 描述 = format!("{} 类型不支持容器方法【{}】", 类型名, 方法名);
    crate::异常运行时::智语言_抛出异常(
        "运行时错误".as_ptr(), "运行时错误".len() as i64,
        描述.as_ptr(), 描述.len() as i64,
    );
}

