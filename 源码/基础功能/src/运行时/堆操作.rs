    /// 取余：规范 §2.6「`%` 返回数学非负余数」（欧几里得，0 ≤ r < |除数|），
    /// 明确不同于 Rust `%` / Cranelift srem（截断，符号跟被除数）——这正是编译器
    /// 【不得】把 `%` 内联为 srem 的原因（见 堆_取余 实现注释）。本测试钉死数学取余语义。
    #[test]
    fn 取余_语义钉死为数学非负余数() {
        // 规范正例：-11 % 3 == 1；10 % -3 == 1；-11 % -3 == 1
        assert_eq!(堆操作(堆_取余, &[整(-11), 整(3)]).整数, 1, "规范 -11 % 3 应为 1");
        assert_eq!(堆操作(堆_取余, &[整(10), 整(-3)]).整数, 1, "数学 10 % -3 应为 1（0≤1<3）");
        assert_eq!(堆操作(堆_取余, &[整(10), 整(3)]).整数, 1, "规范 10 % 3 应为 1");
        assert_eq!(堆操作(堆_取余, &[整(-11), 整(-3)]).整数, 1, "数学 -11 % -3 应为 1（0≤1<3）");
        assert_eq!(堆操作(堆_取余, &[整(-10), 整(3)]).整数, 2, "数学 -10 % 3 应为 2（-10=3×(-4)+2）");

        for &a in 边界集.iter() {
            for &b in 边界集.iter() {
                if b == 0 { continue; }
                let r = 堆操作(堆_取余, &[整(a), 整(b)]);
                assert_eq!(r.标签, 标签_整数, "整数 % 整数 必须产出整数: {} % {}", a, b);
                // 数学取余：余数恒非负（0 ≤ r < |除数|），与除数符号无关
                assert!(
                    r.整数 >= 0,
                    "堆_取余 符号漂移（须为非负）: {} % {} = {}", a, b, r.整数
                );
                // 余数绝对值严格小于除数绝对值（i64::MIN 用 unsigned_abs 规避溢出）
                assert!(
                    (r.整数 as u64) < b.unsigned_abs(),
                    "堆_取余 余数越界: {} % {} = {}", a, b, r.整数
                );
            }
        }
    }

