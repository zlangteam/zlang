//  ⚡双模式⚡ WS-1 整数快速路径差分守护（契约固化）
//
//  背景：编译器 翻译执行器.rs 对「整数 op 整数」内联 Cranelift iadd/isub/imul，
//        不走 base 运行时（每次整数运算过 C-ABI + 堆锁的开销不可接受）。
//        这使得同一语义存在两份源码：base 的 wrapping_* 与 Cranelift 的机器指令。
//
//  守护策略（本测试块的职责）：把 base 侧的整数语义钉死为可执行断定。
//        Cranelift 的 iadd/isub/imul 在 i64 上就是二进制补码回绕（wrapping），
//        因此只要 base 侧恒等于 wrapping_*，两份实现就在语义上锁死。
//        任何人把 base 改成饱和/检查算术，本测试立刻变红。
//        另一半守护在智语言层：测试/自测案例/算术边界双模.智（双模输出必须逐字节一致）。
