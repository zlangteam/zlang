    /// 覆盖「新对象内嵌新对象 = 移动语义（不额外 +1）」与「级联 −1」两侧。
    ///
    /// ⚠ 断言修正（2026-09-20）：原测试「追加后直接 `堆释放(外层.句柄)`，断言存活 −2」**不成立** ——
    ///   因为 `内层` 同时被**局部变量**持有，而 `堆_数组追加` 按本文件不变量①对「复制**既有**对象引用」
    ///   **显式 +1**（见 `堆_数组追加` 分支的 `引用计数加一(&元素)`，注释原文「容器获得一份元素引用 ⇒ +1」）
    ///   ⇒ 追加后 `内层` 计数 = **2**（变量 1 + 外层字段 1）。
    ///   故只释放 `外层` 时，级联 −1 后 `内层` 计数仍为 1 ⇒ **不应回收**，存活只减少 1（= 回收外层本身）。
    ///   要真正验证「级联回收」，须**先释放变量持有的那份引用**，使 `内层` 仅剩「外层字段」这一份 ⇒
    ///   再释放外层时级联归零 ⇒ 存活 −2（外层 + 内层）。
    #[test]
    fn 释放_级联回收子句柄() {
        let 内层 = 造数组(&[整(1), 整(2)]);
        let 外层 = 造数组(&[]);
        let _ = 堆操作(堆_数组追加, &[外层, 内层]);
        // 释放**变量**持有的内层引用：追加已使「外层字段」持有一份 ⇒ 计数由 2 降为 1（仅外层字段持有）
        堆释放(内层.句柄);
        let (_, 存活前, _, _) = crate::值类型::堆统计();
        堆释放(外层.句柄);
        let (_, 存活后, _, _) = crate::值类型::堆统计();
        assert!(
            存活后 + 2 <= 存活前,
            "释放容器应级联回收内部子对象：存活前={} 存活后={}",
            存活前,
            存活后
        );
    }

