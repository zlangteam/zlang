/// ★ 2026-09-27（**F12 修复**）：**整数对的精确比较**（i64，不经 f64）。
///
/// **为什么必须独立**：`堆_小于/堆_小于等于/堆_大于/堆_大于等于` 原先**一律** `转数字 → f64` 比较 ⇒
///   **绝对值 > 2^53 的整数对丢精度**。实测（双模一致）：
///     `甲=9007199254740993, 乙=9007199254740992` ⇒ `甲 > 乙` 判 **假** ✗（应为真）、
///     `甲 >= 乙` 判 **真**（恰好正确）、`甲 < 乙` 判假（恰好正确）、`甲 - 乙 = 1` ✓ ——
///     即两个 f64 相等（同为 9007199254740992.0）导致的**严格比较失真**。
///   而同一对 `==` 走 `堆_实例相等`（i64）⇒ **正确** ✓ ⇒ 四个运算**语义互相不一致** ✗。
///   ⚠ 因解释 VM 与编译器（`翻译执行器`）**都委托本文件**，该缺陷是**双模一致地错**，
///     任何双模门禁都查不出来（本缺口由「标准库边界覆盖用例 183」实测暴露）。
///
/// **契约**：`Some(结果)` = 两侧均为整数、已按 i64 精确比较；`None` = 含小数或非数值
///   ⇒ 交回调用方走原 `转数字`/f64 路径（**对小数/混合/文本比较零行为变化** ✓）。
#[inline]
fn 整数对精确比较(a: &运行时值, b: &运行时值, 序: impl Fn(i64, i64) -> bool) -> Option<运行时值> {
    if a.标签 == 标签_整数 && b.标签 == 标签_整数 {
        Some(运行时值::逻辑(序(a.整数, b.整数)))
    } else {
        None
    }
}

/// 🆕 P1 引用计数（存储侧 +1）：**新产生一份对既有堆对象的引用** ⇒ 计数 +1；非句柄（标量/空值）无操作。
///
/// 与 `值类型.rs::堆释放`（−1）严格成对。触发点 = 「**不深拷贝的持有**」：
///   ① 容器元素存储（数组追加 / 索引存储 / 映射存储）② 结构体字段存储
///   ③ COW 浅克隆（新容器复制了旧容器的子句柄 ⇒ 新容器成为新的持有者）
///
/// 与之对称的 −1（`堆释放`）落点：覆盖旧值 / 删除 / 清空 / 容器回收时的级联释放。
///
/// 【为什么必须有这一侧】容器元素与结构体字段此前"存裸句柄、不计数" ⇒
///   ① `共享计数` 恒为 1 ⇒ COW 永不触发 ⇒ 共享对象被就地修改（值语义外观失效）；
///   ② 级联释放（父对象回收时对子句柄 −1）**无中生有**地减掉了"别人仍持有的引用"
///      ⇒ 实测：`甲 = [车1]` 后访问原变量 `车1` 即崩（`P0定位_变体矩阵.智` 变体 2）。
/// 🆕 2026-10-12（**缺陷C1**：读出的文本在源被销毁后悬垂）：
/// **读取「映射值」时，若命中值是文本 ⇒ 为读取方 +1（共享计数）**。
///
/// 依据（规范/方案原文）：文本 = 值语义的**不可变**堆对象，"表示上允许共享（+1），语义上不可区分"
///   ⇒ 读取方持有计数后，源被 清空/删除/整体覆盖 时其 −1 不会把仍被引用的文本释放掉。
/// 实测机制（探针28 C1/A1/C4）：`甲.内.获取(键)`（接收者是**多级投影**）会经临时副本，副本消亡即 −1，
///   而读取方未计数 ⇒ 悬垂；而 `地.获取(键)`（接收者是局部变量）源存活 ⇒ 正常。
/// 边界：**仅文本** —— 复合值走深拷贝（独立副本）⇒ 加计数反而泄漏；标量无句柄 ⇒ no-op。
pub fn 文本读取加引用(v: &运行时值) {
    if v.标签 != 标签_句柄 {
        return;
    }
    let mut 是文本 = false;
    let _ = 堆读取借用(v.句柄, |数据| {
        是文本 = matches!(数据, 堆数据::文本(_) | 堆数据::文本_静态(..));
    });
    if 是文本 {
        引用计数加一(v);
    }
}

fn 引用计数加一(v: &运行时值) {
    if v.标签 == 标签_句柄 {
        堆增加引用(v.句柄);
    }
}

/// 真值判定：逻辑/整数按非零为真（与解释器 vm.逻辑 语义一致）。
pub fn 真值(v: &运行时值) -> bool {
    match v.标签 {
        标签_逻辑 => v.整数 != 0,
        标签_整数 => v.整数 != 0,
        _ => false,
    }
}

/// 递归深拷贝一个全局堆对象：克隆数据，并对其中嵌套的句柄再次深拷贝。
/// 🆕 统一架构: 支持 闭包环境
fn 深拷贝句柄(id: u64) -> u64 {
    let 数据 = match 堆读取(id) {
        Some(d) => d,
        None => return id,
    };
    let 新数据 = match 数据 {
        堆数据::文本(s) => 堆数据::文本(s),
        // 静态文本深拷贝时升级为拥有 String（COW 落堆）
        堆数据::文本_静态(p, n) => {
            let 切片 = unsafe { std::slice::from_raw_parts(p as *const u8, n) };
            堆数据::文本(String::from_utf8_lossy(切片).into_owned())
        }
        堆数据::数组(arr) => 堆数据::数组(
            arr.iter()
                .map(|v| if v.标签 == 标签_句柄 { 运行时值::句柄(深拷贝句柄(v.句柄)) } else { v.clone() })
                .collect(),
        ),
        堆数据::映射(m) => 堆数据::映射(
            m.iter()
                .map(|(k, v)| {
                    let 新v = if v.标签 == 标签_句柄 { 运行时值::句柄(深拷贝句柄(v.句柄)) } else { v.clone() };
                    (k.clone(), 新v)
                })
                .collect(),
        ),
        堆数据::结构体 { 类型索引, 字段值 } => 堆数据::结构体 {
            类型索引,
            字段值: 字段值
                .iter()
                .map(|v| if v.标签 == 标签_句柄 { 运行时值::句柄(深拷贝句柄(v.句柄)) } else { v.clone() })
                .collect(),
        },
        堆数据::闭包环境 { 函数索引, 捕获变量 } => 堆数据::闭包环境 {
            函数索引,
            捕获变量: 捕获变量
                .iter()
                .map(|v| if v.标签 == 标签_句柄 { 运行时值::句柄(深拷贝句柄(v.句柄)) } else { v.clone() })
                .collect(),
        },
    };
    堆分配(新数据)
}

