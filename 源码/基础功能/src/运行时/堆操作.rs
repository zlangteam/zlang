/// ⚡双模式⚡ 整数算术快速路径唯一真相（单源）。
///
/// 解释器（`虚拟机核心.rs` 的 `二元整数算术`）与编译器（`翻译执行器.rs` 整数快速路径）
/// 的整数 + / - / * 一律经此函数，禁止在两后端各自内联 `wrapping_add/sub/mul` / `iadd/isub/imul`。
/// 一旦 base 调整整数溢出语义（例如 wrapping → checked 抛异常），两后端自动跟随，
/// 从结构上消除"三份内联靠注释对齐"的分叉风险。
///
/// 注意：本函数只处理「整数 OP 整数」的快速路径（不产生可捕获异常），
/// 其余类型（小数/混合/文本拼接）仍由 `堆操作(堆_加法/减法/乘法, ...)` 全量分派处理。
pub fn 整数算术(操作码: usize, a: i64, b: i64) -> i64 {
    match 操作码 {
        堆_加法 => a.wrapping_add(b),
        堆_减法 => a.wrapping_sub(b),
        堆_乘法 => a.wrapping_mul(b),
        _ => 0,
    }
}

/// 位运算操作数类型错误 ⇒ **抛可捕获异常**（不再静默返回空值）。
///
/// ⚠ 2026-10-22 实测缺陷（F49）：`1.5 & 1` / `1.5 << 1` / `~1.5` 曾**静默返回空值**，
///   下游 `转文本(空值)` 才抛「空值不能参与类型转换」⇒ 用户看不出真实原因是"位运算只接受整数"。
///   规范 §2.6.4：位运算符用于对**整数**做二进制位操作 ⇒ 非整数必须明确报错。
///   本函数是 6 个位运算 opcode 的**唯一**错误出口（解释/编译共用 base ⇒ 双模天然一致）。
fn 位运算类型错误(运算: &str, 值: &运行时值) -> 运行时值 {
    let 类型名 = match 值.标签 {
        标签_小数 => "小数",
        标签_逻辑 => "逻辑",
        标签_空值 => "空值",
        标签_句柄 => "文本/容器",
        _ => "非整数",
    };
    let 消息 = format!("位运算 {} 仅支持整数（操作数实际类型：{}）", 运算, 类型名);
    crate::异常运行时::智语言_抛出异常(
        "类型错误".as_ptr(),
        "类型错误".len() as i64,
        消息.as_ptr(),
        消息.len() as i64,
    );
    运行时值::空值()
}
