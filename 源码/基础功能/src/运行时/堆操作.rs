            // 若仍返回旧 id 则调用方持有的句柄指向未修改的旧副本（泛型结构体字段映射/数组经多次访问触发）。
            // 先以 堆_写入前复制 拿到 COW 后的真实 id（共享=1 时即原 id），再在其上修改并返回真实 id。
