pub fn 执行(参数: &[String]) {
    let 输出到当前 = 参数解析::提取输出目录标志(参数);
    let 文件路径 = 参数解析::提取文件路径(参数);

    match 文件路径 {
        None => {
            if 输出到当前 {
                eprintln!("[智语言] 错误：./ 参数需要指定源文件");
                return;
            }
            // 无文件参数 → 项目模式
            执行项目模式(参数);
        }
        Some(路径) => {
            // ★规范 §3.7.4「单文件路径」前置校验（路径级中文命名强制检查）
            if !crate::命名校验::校验源文件路径(&路径) {
                std::process::exit(1);
            }
            // 有文件参数 → 单文件模式
            执行单文件模式(&路径, 参数, 输出到当前);
        }
    }
}

/// 项目模式：查找项目配置，运行入口
fn 执行项目模式(参数: &[String]) {
    match 项目检测::检测当前目录项目归属() {
        项目归属::项目内(根目录) => {
            let 入口文件 = 项目源文件::查找入口(&根目录);

            let 入口路径 = match 入口文件 {
                Some(f) => f,
                None => {
                    eprintln!("[智语言] 错误：项目中未找到 启动程序 定义");
                    return;
                }
            };

            let 是否调试 = 参数解析::有标志(参数, "--调试");
            let 是否跳过缓存 = 参数解析::有标志(参数, "--跳过缓存");

            // 项目内 → 产物放 产出/字节码文件/  (优先读 项目.配置)
            let 输出配置 = pm::产物路径::解析项目输出配置(&根目录);
            let 缓存目录 = 输出配置.源码字节码文件.clone();
            let mut 缓存管理器 = 缓存管理器::新建_项目级(根目录.clone());
            缓存管理器.缓存目录 = 缓存目录.clone();

            // 1) 缓存路径（规范 6.2.4：入口源码 源码/启动程序.智 → 产出/字节码文件/启动程序.字节码）
            let 入口路径对象 = std::path::Path::new(&入口路径);
            let 相对路径 = 项目源文件::计算相对路径(&入口路径, &根目录);
            let 缓存文件路径 = {
                let 父 = 相对路径.parent().map(|p| 缓存目录.join(p)).unwrap_or(缓存目录.clone());
                let 主干 = 入口路径对象.file_stem().map(|n| format!("{}.字节码", n.to_string_lossy())).unwrap_or_default();
                父.join(&主干)
            };
            fs::create_dir_all(缓存文件路径.parent().unwrap_or(&缓存目录)).ok();

            // 2) 编译源码 — 始终执行降级+FFI注册，使缓存命中也能正确注册外部函数
            let 源文件列表 = 项目源文件::收集(&根目录);
            if 源文件列表.is_empty() {
                eprintln!("[智语言] 错误：项目中未找到 .智 源文件");
                // ★ 2026-09-27（工具链修复）：失败路径 ⇒ 非零退出码（原为 rc=0 ✗）。
                std::process::exit(1);
            }
            let 源码 = match fs::read_to_string(&入口路径) {
                Ok(s) => s,
                Err(e) => {
                    eprintln!("[智语言] 错误：无法读取文件 '{}': {}", 入口路径, e);
                    // ★ 2026-09-27（工具链修复）：同上一律非零退出码（原为 rc=0 ✗，
                    //   实测「不存在的文件」在解释模式下退出码为 0，会骗过只看 rc 的 CI）。
                    std::process::exit(1);
                }
            };
            let 底层表示模块 = match 编译并降级(&源码, &入口路径) {
                Some(m) => m,
                // ★ 2026-09-27（工具链修复）：运行/降级失败 ⇒ **非零退出码**（原为 rc=0 ✗，
                //   与编译失败同源问题：只看退出码的 CI 会把失败当成功）。
                None => { eprintln!("[智语言] 运行失败"); std::process::exit(1); }
            };
            注册外部函数(&底层表示模块, &根目录);

            // 3) 字节码缓存检查：签名一致（源集合哈希 | 配置版本 | 前端指纹 | 基础指纹）则直接执行
            //    —— 与单文件模式共用同一套失效判定，消除「项目模式只查魔数头」的裸分支。
            //    签名第三部分起由「构建期烧入的内容指纹」驱动，改任意前端源码必然失效，无需手动 bump 版本。
            let 签名文件 = 缓存文件路径.with_extension("字节码.构建签名");
            // 末段「帧释」：前端按 帧级释放启用()（环境变量开关）决定是否发射逐槽释放指令，
            // 虚拟机按同一开关决定弹帧时是否批量释放。开关不进签名时，换开关后命中旧缓存
            // 会重复释放（对象被提前回收、读到空值）或全部泄漏。
            let 完整构建签名 = format!("{}|{}|{}|{}|{}|帧释{}",
                缓存管理器::计算源集合哈希(&入口路径, false),
                pm::全局配置::当前激活版本(),
                crate::构建签名::前端指纹(),
                crate::构建签名::基础指纹(),
                crate::构建签名::解释器指纹(),
                base::值类型::帧级释放启用() as u8);
            if !是否跳过缓存 && !是否调试 && 缓存文件路径.exists() {
                if let Some(缓存的字节码) = 读取字节码缓存(&缓存文件路径, &签名文件, &完整构建签名) {
                    eprintln!("[智语言] 字节码（缓存命中）：{}", 缓存文件路径.display());
                    执行字节码(&缓存的字节码, 是否调试);
                    return;
                }
            }

            // 4) 未命中：生成字节码并缓存
            let 字节码 = match 字节码生成器::新建().生成(&底层表示模块) {
                Ok(b) => b,
                Err(e) => { eprintln!("[智语言] 字节码生成失败: {}", e); std::process::exit(1); }
            };
            eprintln!("[智语言] 字节码：{}", 缓存文件路径.display());

            if !是否跳过缓存 && !是否调试 {
                写入字节码缓存(&缓存文件路径, &签名文件, &完整构建签名, &字节码);
            }

            执行字节码(&字节码, 是否调试);
        }
        项目归属::项目外 => {
            eprintln!("[智语言] 错误：未指定源文件，且当前目录不是项目根目录（未找到 配置/项目.配置）");
        }
    }
}

/// 单文件模式
fn 执行单文件模式(文件路径: &str, 参数: &[String], 输出到当前: bool) {
    let 是否调试 = 参数解析::有标志(参数, "--调试");
    let 是否跳过缓存 = 参数解析::有标志(参数, "--跳过缓存");
    let 是否直接执行 = 参数解析::有标志(参数, "--直接执行");

    // --直接执行 与 --调试 互斥
    if 是否直接执行 && 是否调试 {
        eprintln!("[智语言] 错误：--直接执行 与 --调试 不能同时使用");
        return;
    }

    let 源码 = match fs::read_to_string(&文件路径) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[智语言] 错误：无法读取文件 '{}': {}", 文件路径, e);
            // ★ 2026-09-27（工具链修复）：单文件模式读失败 ⇒ 非零退出码（原为 rc=0 ✗）。
            std::process::exit(1);
        }
    };

    // 降级为底层表示模块（始终执行，以注册外部函数 FFI）
    let 底层表示模块 = match 编译并降级(&源码, &文件路径) {
        Some(m) => m,
        None => {
            eprintln!("[智语言] 运行失败");
            // ★ 2026-09-27（工具链修复）：同项目模式——失败 ⇒ 非零退出码（原为 rc=0 ✗）。
            std::process::exit(1);
        }
    };
    // 🆕 FFI: 注册外部函数到运行时（双模式共用真相）
    //  项目根从入口文件路径检测（单文件可能在项目内，用于定位 项目/产出/执行文件/ 下的外部库）
    let 项目归属 = 项目检测::查找项目根目录(文件路径);
    let 默认项目根 = std::path::Path::new(".");
    let 项目根引用 = 项目归属.as_deref().unwrap_or(默认项目根);
    注册外部函数(&底层表示模块, 项目根引用);

    // 纯解释执行，不生成字节码
    if 是否直接执行 {
        let 字节码 = match 字节码生成器::新建().生成(&底层表示模块) {
            Ok(b) => b,
            Err(e) => { eprintln!("[智语言] 字节码生成失败: {}", e); return; }
        };
        执行字节码(&字节码, 是否调试);
        return;
    }

    let 项目归属 = 项目检测::查找项目根目录(文件路径);

    // 单文件字节码落点：项目内 → 产出/字节码文件/<相对路径>.字节码；项目外 → 全局缓存目录
    let (缓存目录, 相对路径) = match &项目归属 {
        Some(根) => {
            // 项目内 → 产物放 产出/字节码文件/（优先读 项目.配置）
            let 输出配置 = pm::产物路径::解析项目输出配置(根);
            (输出配置.源码字节码文件, 项目源文件::计算相对路径(文件路径, 根))
        }
        None => {
            if 输出到当前 {
                // 🆕 G3: ./ 标记 → 字节码输出到当前目录
                let 当前目录 = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
                let 文件主干 = PathBuf::from(文件路径).file_stem()
                    .map(|n| format!("{}.字节码", n.to_string_lossy()))
                    .unwrap_or_default();
                let 字节码 = match 字节码生成器::新建().生成(&底层表示模块) {
                    Ok(b) => b,
                    Err(e) => { eprintln!("[智语言] 字节码生成失败: {}", e); return; }
                };
                let 输出路径 = 当前目录.join(&文件主干);
                fs::write(&输出路径, &字节码).ok();
                eprintln!("[智语言] 字节码：{}", 输出路径.display());
                执行字节码(&字节码, 是否调试);
                return;
            }
            // 项目外 → 全局缓存（.智语言/产出/字节码文件/）
            let 缓存目录 = 缓存管理器::新建().缓存目录;
            (缓存目录.canonicalize().unwrap_or(缓存目录), PathBuf::new())
        }
    };

    // 缓存路径（plain 命名 + 构建签名，与编译命令增量构建一致：
    // 源码未修改时复用已有字节码，修改后自动重建）
    let 父目录 = 相对路径.parent().map(|p| 缓存目录.join(p)).unwrap_or(缓存目录.clone());
    fs::create_dir_all(&父目录).ok();
    let 文件主干 = PathBuf::from(文件路径).file_stem()
        .map(|n| format!("{}.字节码", n.to_string_lossy()))
        .unwrap_or_default();
    let 缓存文件路径 = 父目录.join(&文件主干);
    let 签名文件 = 缓存文件路径.with_extension("字节码.构建签名");
    // 末段「帧释」见项目模式同名签名处的说明。
    let 完整构建签名 = format!("{}|{}|{}|{}|{}|帧释{}",
        缓存管理器::计算源集合哈希(文件路径, false),
        pm::全局配置::当前激活版本(),
        crate::构建签名::前端指纹(),
        crate::构建签名::基础指纹(),
        crate::构建签名::解释器指纹(),
        base::值类型::帧级释放启用() as u8);

    // 缓存命中：构建签名一致则复用已有字节码
    if !是否跳过缓存 && !是否调试 && 缓存文件路径.exists() {
        if let Some(缓存的字节码) = 读取字节码缓存(&缓存文件路径, &签名文件, &完整构建签名) {
            eprintln!("[智语言] 字节码（缓存命中）：{}", 缓存文件路径.display());
            执行字节码(&缓存的字节码, 是否调试);
            return;
        }
    }

    // 未命中：生成字节码并缓存
    let 字节码 = match 字节码生成器::新建().生成(&底层表示模块) {
        Ok(b) => b,
        Err(e) => { eprintln!("[智语言] 字节码生成失败: {}", e); std::process::exit(1); }
    };
    eprintln!("[智语言] 字节码：{}", 缓存文件路径.display());
    if !是否跳过缓存 && !是否调试 {
        写入字节码缓存(&缓存文件路径, &签名文件, &完整构建签名, &字节码);
    }
    执行字节码(&字节码, 是否调试);
}


/// 前端流水线降级到底层表示模块（使用统一入口）
fn 编译并降级(源码: &str, 文件路径: &str) -> Option<底层表示模块> {
    let mut 诊断 = 诊断收集器::新建();
    frontend::诊断全局::设置诊断模式_自CLI(&mut 诊断);
    let 配置 = 前端流水线配置::新建(文件路径, 源码);
    let 结果 = 执行前端流水线_兼容(&配置, &mut 诊断);
    if 结果.is_none() {
        输出诊断(&诊断);
    }
    结果
}

    // 🆕 FFI: 注册外部函数到运行时（双模式共用单翻译器 模块到FFI项）
    //  项目根：由调用方从入口文件路径检测后传入（单文件/项目模式一致），用于定位
    //  项目/产出/执行文件/ 下的动态外部库(.dll/.lib)，加入 shim 搜索路径。
/// FFI：注册外部函数到运行时（解释模式单一真相）。
/// `pub(super)` 供兄弟模块 `测试命令` 复用 —— `测试` 命令若不注册，外部函数调用会
/// 报「调用 索引=401 未注册」（此前 `运行` 通过而 `测试` 失败的根因）。
pub(super) fn 注册外部函数(模块: &底层表示模块, 项目根: &std::path::Path) {
    base::外部调用注册::清空外部函数表();
    // 🆕 G1：外部结构体布局必须先于函数注册写入布局表——
    // shim 元数据构造时按「精确码 21 + 结构体名」查表还原 #[repr(C)] 布局，
    // 布局缺失会静默退化为不透明指针（结构体参数/返回值随即失效）。
    for 布局 in 公共降级::模块到FFI结构体布局(模块) {
        base::外部调用注册::注册外部结构体布局(布局.名称, 布局.字段类型码);
    }
    // ★补全库标识 → 物理路径映射：底层模块.库映射表 里的路径是语法期的相对代号（如 "gtk4"），
    // 未补全为绝对路径；而 外部语言映射（来自 项目依赖.配置 锁文件 + 补全依赖路径）才是
    // 补全后的真实绝对路径（如 项目根/外部语言/GTK4/）。用外部语言映射补全，才能把
    // GTK4/bin/gtk4.dll 所在子目录加入 -L（rustc -L 非递归），否则 raw-dylib 找不到 gtk4.dll。
    // ★规范 §6.5.2：`导入 <代号>` 里的**代号只是项目内唯一标识**，真实库名写在
    //   项目.配置 的 `原始名` 字段（"镜像源或系统中的真实库名"）。链接与运行期加载必须用
    //   原始名——例如 `导入 图形对象`/`导入 gobject` 对应真实 DLL `gobject-2.0-0.dll`。
    //   过去 #[link(name=..)] 直接用代号，代号≠原始名时 shim 会去找不存在的 <代号>.dll，
    //   运行期报错找不到模块；这里统一把代号翻译成原始名后再交给 FFI 注册。
    let 物理路径映射: std::collections::HashMap<String, std::path::PathBuf> = {
        let mut m = std::collections::HashMap::new();
        if let Ok(方案) = pm::依赖解析::构建模块解析方案(项目根, false) {
            for 条目 in &方案.外部语言映射 {
                if let Some(路径) = &条目.路径 {
                    m.insert(条目.代号.clone(), 路径.clone());
                    m.insert(条目.原始名.clone(), 路径.clone());
                }
            }
        }
        m
    };
    // ★2026-08-10 传递依赖 DLL 加载：记录外部语言目录型依赖（如 GTK4）的 运行时 bin 子目录，
    //   供 shim cdylib 加载时临时加入 DLL 搜索路径。解释模式 shim 经 raw-dylib 静态引用 gtk4.dll 等，
    //   而这些 dll 在 库/.../GTK4/bin/，既不位于 shim 自身目录也不在系统目录，
    //   且 LoadLibraryExW 的 DEFAULT_DIRS 标志排除 PATH/调用方目录 → 加载失败 → GTK 无法调用。
    //   修复=加载 shim 前把各外部语言的 bin/ 目录经 SetDllDirectoryW 临时加入搜索路径（加载后还原）。
    let mut 外部语言二进制目录: Vec<std::path::PathBuf> = Vec::new();
    // 单一真相：与编译模式共用 编译命令::构建外部库链接名映射。
    let 链接名映射 = crate::编译命令::构建外部库链接名映射(项目根);
    let mut 静态库列表: Vec<std::path::PathBuf> = Vec::new();
    for 项 in 公共降级::模块到FFI项(模块) {
        // 真实C ABI（原生约定=true，含静态链接与动态 raw-dylib）= 走 shim 统一入口；
        // 智语言扁平约定（原生约定=false）= transmute 回退路径。
        // 🆕 是否静态由 项目依赖.配置 锁路径扩展名推导（2026-08-07 定稿：取代 静态/原始 关键字，
        //   双模式共享 编译命令::推导外部语言是否静态 单一真相）。
        let 是否静态 = crate::编译命令::推导外部语言是否静态(&项.库标识, 项目根);
        let 原生约定 = 项.原生约定;
        // ★规范 §6.5.3：无论静态/动态，外部库 dll/.lib 所在目录均加入 shim 搜索路径。
        //   静态库取 .lib 导入库目录；动态库（原始）取 .dll（同目录预生成 .lib 导入库）目录。
        if 原生约定 {
            // ★优先用 外部语言映射 补全后的物理绝对路径；降级层库映射表里的代号相对路径作回退。
            let 路径 = 物理路径映射
                .get(&项.库标识)
                .cloned()
                .or_else(|| 模块.库映射表.get(&项.库标识).map(|(p, _, _)| std::path::PathBuf::from(p)));
            if let Some(路径) = 路径 {
                静态库列表.push(路径.clone());
                // 记录 bin/ 子目录（GTK4 的 gtk4.dll 等运行时 dll 所在），供 shim 加载时加入搜索路径
                let bin目录 = 路径.join("bin");
                if bin目录.is_dir() && !外部语言二进制目录.iter().any(|p| *p == bin目录) {
                    外部语言二进制目录.push(bin目录);
                }
            }
        }
        // 代号 → 原始名（真实库名）；未配置 原始名 时代号即真实库名。
        let 链接库名 = 链接名映射.get(&项.库标识).cloned().unwrap_or_else(|| 项.库标识.clone());
        base::外部调用注册::注册外部函数(base::外部调用注册::FFI项 {
            键: 项.键,
            c符号: 项.c符号.clone(),
            库标识: 链接库名,
            形参标签: 项.形参标签.clone(),
            返回标签: 项.返回标签,
            输出位图: 项.输出位图.clone(),
            是否静态,
            原生约定,
            形参C类型: 项.形参C类型.clone(),
            返回C类型: 项.返回C类型,
            函数指针形状: 项.函数指针形状.clone(),
            形参结构体名: 项.形参结构体名.clone(),
            返回结构体名: 项.返回结构体名.clone(),
            是否全局变量: 项.是否全局变量,
            形参数组元素C类型: 项.形参数组元素C类型.clone(),
            形参数组长度索引: 项.形参数组长度索引.clone(),
        });
    }
    // 存在真实C ABI（原生约定=true，静态或动态）外部函数时，构建并加载 shim（双模式统一入口）
    if 模块.库映射表.values().any(|(_, _, 原生)| *原生) {
        let mut 静态库搜索目录: Vec<std::path::PathBuf> =
            静态库列表.iter()
                .filter_map(|p| p.parent())
                .filter(|d| !d.as_os_str().is_empty())
                .map(|d| d.to_path_buf())
                .collect();
        // ★规范 §6.5.3：外部语言静态库产物在 项目根/产出/外部语言文件/，
        // 加入 shim 的 -L 搜索路径（2026-08-05 学生点名系统：sqlite3.lib 需被 #[link] 解析）。
        let 输出配置 = pm::产物路径::解析项目输出配置(项目根);
        let 外部语言产物 = 输出配置.外部语言文件.join("编译文件");
        if 外部语言产物.exists() && !静态库搜索目录.contains(&外部语言产物) {
            静态库搜索目录.push(外部语言产物);
        }
        let 外部语言目录 = 项目根.join("外部语言");
        if 外部语言目录.exists() && !静态库搜索目录.contains(&外部语言目录) {
            静态库搜索目录.push(外部语言目录);
        }
        // ★ rustc `-L` 非递归，而规范 §6.5.4 的布局是 `外部语言/<库名>/<库名>.dll`：
        //   必须把一级子目录一并入列，否则 shim 生成/编译期的「按库名搜索 + 落非 ASCII 安全名副本」
        //   找不到库 ⇒ shim 加载 os_err=126（实测：解释模式首次运行即失败）。
        for 子目录 in pm::依赖解析::外部语言一级子目录(项目根) {
            if !静态库搜索目录.contains(&子目录) {
                静态库搜索目录.push(子目录);
            }
        }
        // ★目录型外部库（如 GTK4：gtk4.dll 在 bin/、导入库在 lib/）的 .dll/.lib 不在库根目录，
        // 而在其子目录。rustc -L 非递归，需显式把含 .dll/.lib 的子目录（bin/、lib/）加入搜索路径，
        // 否则 raw-dylib 找不到 gtk4.dll、shim 编译失败、运行时报「FFI 包装（shim）未加载」。
        for 库路径 in 静态库列表.iter() {
            if 库路径.is_dir() {
                for 子名 in ["bin", "lib", "Bin", "Lib"] {
                    let 子目录 = 库路径.join(子名);
                    if 子目录.exists()
                        && 子目录.is_dir()
                        && !静态库搜索目录.contains(&子目录)
                    {
                        静态库搜索目录.push(子目录);
                    }
                }
            }
        }
        // ★规范 §6.5.3：动态外部库（.dll，无导入库）的导入库(.lib)与 dll 同目录部署于
        //   项目 产出/执行文件/，加入 shim 的 -L 搜索路径，使 #[link(kind="dylib")] 可解析符号。
        let 执行文件目录 = 输出配置.执行文件;
        if 执行文件目录.exists() && !静态库搜索目录.contains(&执行文件目录) {
            静态库搜索目录.push(执行文件目录);
        }
        // ★2026-08-10 加载 shim 前把外部语言运行时 bin 目录加入 DLL 搜索路径：
        // 解释模式 shim 经 raw-dylib 静态引用 gtk4.dll 等，而这些 dll 在 库/.../GTK4/bin/，
        // 既不位于 shim 自身目录也不在系统目录，LoadLibraryExW 的 DEFAULT_DIRS 标志又排除 PATH→加载失败。
        // 修复=经 SetDllDirectoryW 临时加入各外部语言 bin/ 目录（加载后还原），与 静态库搜索目录 互补
        // （-L 解决「编译期找符号」，SetDllDirectory 解决「运行期加载 dll」）。
        for 库路径 in 静态库列表.iter() {
            if 库路径.is_dir() {
                for 子名 in ["bin", "Bin"] {
                    let bin目录 = 库路径.join(子名);
                    if bin目录.is_dir() {
                        base::外部调用注册::设置外部库搜索目录(&bin目录);
                    }
                }
            }
        }
        // ★修复双嵌套路径：生成并编译shim 内部会再 join("外部语言文件").join("执行文件")，
        // 故此处只传 全局外部语言根（全局/产出），得到单嵌套 全局/产出/外部语言文件/执行文件。
        // 双嵌套（外部语言文件/执行文件 重复）会导致 LoadLibrary 中文长路径失败（os_err=126）。
        let shim目录 = pm::目录::全局目录().join("产出");
        let shim目录字符串 = shim目录.to_string_lossy().to_string();
        if let Err(e) = base::外部调用注册::生成并编译shim(&shim目录字符串, &静态库搜索目录) {
            eprintln!("[智语言] 警告：FFI shim 生成失败（真实C ABI 不可用）: {}", e);
        } else {
            eprintln!("[智语言] 调试：FFI shim 生成成功");
        }
    }
}

// ── 字节码缓存的读写 ──
// 缓存由「字节码文件 + 签名文件」两个文件组成。旧实现分两次直接覆盖写、命中时只比签名：
//   · 单文件模式的缓存按文件名落在同一目录，两个同名源文件并发运行时可能留下
//     「甲的签名 + 乙的字节码」，之后运行甲会命中缓存、执行乙的程序；
//   · 写到一半被中断会留下截断的字节码。
// 现在签名里附带字节码内容哈希，命中时一并校验；两个文件都先写临时文件再改名。
fn 字节码缓存签名(构建签名: &str, 字节码: &[u8]) -> String {
    use std::hash::{Hash, Hasher};
    let mut 哈希器 = std::collections::hash_map::DefaultHasher::new();
    字节码.hash(&mut 哈希器);
    format!("{}|内容{:016x}", 构建签名, 哈希器.finish())
}

fn 读取字节码缓存(缓存文件路径: &std::path::Path, 签名文件: &std::path::Path, 构建签名: &str) -> Option<Vec<u8>> {
    let 上次签名 = fs::read_to_string(签名文件).ok()?;
    // 先用构建签名前缀快速排除，避免每次未命中都读整份字节码
    if !上次签名.trim().starts_with(构建签名) { return None; }
    let 字节码 = fs::read(缓存文件路径).ok()?;
    if 字节码.len() < 4 || &字节码[0..4] != &0x43534C42u32.to_le_bytes() { return None; }
    if 上次签名.trim() != 字节码缓存签名(构建签名, &字节码) { return None; }
    Some(字节码)
}

fn 写入字节码缓存(缓存文件路径: &std::path::Path, 签名文件: &std::path::Path, 构建签名: &str, 字节码: &[u8]) {
    fn 原子写入(路径: &std::path::Path, 内容: &[u8]) -> bool {
        let mut 临时名 = 路径.as_os_str().to_owned();
        临时名.push(format!(".临时{}", std::process::id()));
        let 临时路径 = std::path::PathBuf::from(临时名);
        if fs::write(&临时路径, 内容).is_err() { let _ = fs::remove_file(&临时路径); return false; }
        if fs::rename(&临时路径, 路径).is_err() { let _ = fs::remove_file(&临时路径); return false; }
        true
    }
    // 缓存只是加速手段：写失败（只读目录、磁盘满）不影响本次执行，但要撤掉签名以免下次误命中
    if !原子写入(缓存文件路径, 字节码)
        || !原子写入(签名文件, 字节码缓存签名(构建签名, 字节码).as_bytes())
    {
        let _ = fs::remove_file(签名文件);
    }
}

/// 执行字节码（解释模式）
fn 执行字节码(字节码: &[u8], 是否调试: bool) {
    let mut 虚拟机实例 = 虚拟机::新建();
    // 「运行」不设步数上限：默认的 10 亿步上限会把合法的长时间程序（服务循环、重计算，
    // 实测约 13 秒）当成“可能无限循环”强行终止，而编译模式没有这个限制。
    // 「测试」命令按用例超时自行设置上限，不受影响。
    虚拟机实例.最大步数 = u64::MAX;
    if 是否调试 {
        虚拟机实例.调试器 = Some(调试器::新建());
        eprintln!("[智语言] 调试模式已启动");
    }
    虚拟机实例.加载字节码(字节码);
    // ★ 2026-10-02（**F28 修复**）：解释模式**顶层未捕获异常 ⇒ 非零退出码** ✗→✓
    //   原先 VM 打印异常后正常返回 ⇒ 工具链 rc=0 ✗（与编译模式同病）⇒ 崩溃被当成功。
    //   先清标志（防残留），执行后判定 ⇒ 有 ⇒ exit(1) ✓
    base::异常运行时::顶层未捕获异常_清();
    虚拟机实例.执行();
    if base::异常运行时::顶层未捕获异常_取并清() {
        std::process::exit(1);
    }
    // 因步数/时间上限被强行终止也必须是非零退出码（原先打印错误后以 0 退出）
    if 虚拟机实例.异常激活 && 虚拟机实例.异常信息类型 == "超时" {
        std::process::exit(1);
    }
}
