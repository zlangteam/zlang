// 🆕 统一帧契约（UFC）：解释模式根枚举（2026-09-22）
//
// 契约：**帧 = `局部变量表` 的一段连续区间**（`调用帧栈[i].局部变量基址` → 下一帧基址；
//   末帧延伸到 `局部变量表.len()`）。本函数把"当前可见的全部根句柄"喂给 base 的
//   「可达性对账 / 兜底回收」，与编译模式的影子帧链（后续批次）产出**同构根集**：
//   · 各帧区间内的 `局部变量表` 槽（含临时槽，**保守全扫：宁可多标，绝不漏标**）
//   · `全局变量表`
//   · `操作数栈`（临时寄存器，保守纳入）
//   · 并发任务快照 `任务表[*]` 与 `主任务_保存`（**在途对象必须计为根**，否则会被误回收）
//
// ⚠ 只读本线程引擎的帧内存、**绝不取堆锁**（调用点保证在无堆锁上下文，见 值类型.rs 铁律）；
//   ⚠ 线程本地注册（跨线程枚举别人的帧 = 数据竞争，见 值类型.rs `本线程根提供者`）。
// ══════════════════════════════════════════════════════════════════════════════
fn 枚举本虚拟机根(上下文: usize, 回调: &mut dyn FnMut(u64)) {
    if 上下文 == 0 { return; }
    let vm = unsafe { &*(上下文 as *const 虚拟机) };
    let mut 喂 = |v: &运行时值| {
        if v.标签 == base::值类型::标签_句柄 && v.句柄 != 0 {
            回调(v.句柄);
        }
    };
    // ⚠ 曾在此加过 env 门控的**分类诊断**（`智语言_根诊断`：按「帧/全局/操作数栈/任务」分别统计悬垂数）。
    //   结论已固化：悬垂 **100% 来自「帧」**（`114` 帧24/悬19、`14接口` 78/60、`110` 58/42；其余三类恒 0）
    //   ⇒ 修复落点定为「帧消亡时清帧」（见 `虚拟机::清当前帧槽`）。诊断代码已移除（如需复现可照此重建）。
    // ① 各调用帧区间（帧 = 局部变量表的一段；末帧延伸到表尾）
    let mut 界列表: Vec<usize> = vm.调用帧栈.iter().map(|f| f.局部变量基址).collect();
    界列表.push(vm.局部变量表.len());
    let mut 起点 = 0usize;
    for 界 in 界列表 {
        let 止 = 界.min(vm.局部变量表.len());
        for i in 起点..止 { if let Some(v) = vm.局部变量表.get(i) { 喂(v); } }
        起点 = 止;
    }
    // ② 全局变量表
    for v in &vm.全局变量表 { 喂(v); }
    // ③ 操作数栈（临时）
    for v in &vm.操作数栈 { 喂(v); }
    // ⑤ 🆕 阶段 1b（2026-09-22）：**常量池作为根** —— 文本常量是**程序级常量对象**
    //   （与编译模式"统一字面量表"同构）⇒ 纳入根集后：
    //     ① 不再被计为"存活但不可达"（此前 `115` 每任务 ~23 个常量被误判 ⇒ 判据判别力受损）；
    //     ② 兜底清扫（若开启）不会误收常量对象；
    //     ③ 两引擎可达/存活口径**逐项可比**（J2）✓
    //   🔁 阶段 1d（2026-09-23）：只枚举**已物化**项 —— 惰性文本未物化时**没有堆对象**，
    //     故它不是根；这与编译模式"字面量表只登记按使用物化过的字面量"**口径一致** ✓
    for 项 in &vm.常量池 {
        if let 常量池项::值(v) = 项 { 喂(v); }
    }
    // ④ 并发任务快照（在途对象）
    for 任务 in vm.任务表.values() {
        for v in &任务.保存的局部变量表 { 喂(v); }
        for v in &任务.保存的操作数栈 { 喂(v); }
        if let Some(v) = 任务.结果.as_ref() { 喂(v); }
    }
    if let Some((_, locals, stack, _)) = vm.主任务_保存.as_ref() {
        for v in locals { 喂(v); }
        for v in stack { 喂(v); }
    }
}

/// 根提供者 RAII 守卫：`执行()` 期间注册、退出自动注销（与「回调桥守卫」同一模式）。
/// 🆕 2026-09-22（方案 §12.1）：**同时注册"拥有型根提供者"** —— 后者只用于对账**分类**
///   （区分「悬垂(拥有型)=致命」与「悬垂(非拥有型)=良性」），**不参与可达性判定**、
///   也**不计入** `活跃根提供者数`（否则会污染"结果完整性"判定）✓
struct 根提供者守卫(usize, usize);
impl 根提供者守卫 {
    fn 启用(虚拟机指针: usize) -> Self {
        根提供者守卫(
            base::值类型::注册根提供者(虚拟机指针, 枚举本虚拟机根),
            base::值类型::注册拥有型根提供者(虚拟机指针, 枚举本虚拟机拥有型根),
        )
    }
}
impl Drop for 根提供者守卫 {
    fn drop(&mut self) {
        base::值类型::注销根提供者(self.0);
        base::值类型::注销拥有型根提供者(self.1);
    }
}

/// 🆕 2026-09-22（方案 §12.1）**拥有型根枚举**（解释模式）：只喂「各调用帧**拥有型槽**」持有的句柄。
/// 用途：与 `枚举本虚拟机根`（**保守全扫**）对照 ⇒ 把对账 `悬垂引用` 分为
///   「悬垂(**拥有型**)= **致命**：拥有型槽指向已回收对象 —— 语义上不可能合法（计数漏记/提前释放）」；
///   「悬垂(**非拥有型**)= **良性**：借用 / 临时槽的陈旧句柄 —— "借用不长于所有者"，值已不被读取」。
///
/// 帧 → 函数的定位（比 `帧级批量释放` 稍复杂：需覆盖**全部**帧，而非仅被弹的那一帧）：
///   · 栈顶帧：用 `指令指针`（当前执行位置）✓
///   · 其余各帧：用**其上方那一帧的 `返回地址`** —— 内层帧的返回地址必然落在**外层帧所属函数**的代码区间内 ✓
///   ⚠ 定位失败 ⇒ **跳过该帧**。安全性：本提供者**只用于分类**、不参与可达性 ⇒ 少喂只会把该槽的悬垂
///     归入"非拥有型"（**报告方向保守**：不会把致命误标为良性之外的更坏结果），绝不掩盖语义 ✓
fn 枚举本虚拟机拥有型根(上下文: usize, 回调: &mut dyn FnMut(u64)) {
    if 上下文 == 0 { return; }
    let vm = unsafe { &*(上下文 as *const 虚拟机) };
    let 帧数 = vm.调用帧栈.len();
    for i in 0..帧数 {
        let ip = if i + 1 < 帧数 { vm.调用帧栈[i + 1].返回地址 } else { vm.指令指针 };
        let Some(索引) = vm.函数表.iter().position(|f| {
            let 起 = f.代码偏移 as usize;
            ip >= 起 && ip < 起 + f.代码长度 as usize
        }) else { continue };
        let 基址 = vm.调用帧栈[i].局部变量基址;
        for &槽 in vm.函数表[索引].拥有型槽索引.iter() {
            if let Some(v) = vm.局部变量表.get(基址 + 槽) {
                if v.标签 == base::值类型::标签_句柄 && v.句柄 != 0 { 回调(v.句柄); }
            }
        }
    }
}

