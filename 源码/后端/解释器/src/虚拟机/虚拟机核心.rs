/// 预留：JSON → 运行时值 转换（解释器侧当前未接线；如在解释器启用 JSON 解析，属独立功能任务）。
#[allow(dead_code)]
fn 虚拟机的json值到运行时值(json: &serde_json::Value) -> 运行时值 {

    match json {

        serde_json::Value::Null => 运行时值::空值(),

        serde_json::Value::Bool(b) => 运行时值::逻辑(*b),

        serde_json::Value::Number(n) => {

            if let Some(i) = n.as_i64() { 运行时值::整数(i) }

            else if let Some(f) = n.as_f64() { 运行时值::小数(f) }

            else { 运行时值::整数(0) }

        }

        serde_json::Value::String(s) => 分配文本(s.clone()),

        serde_json::Value::Array(arr) => {

            let vals: Vec<运行时值> = arr.iter().map(|v| 虚拟机的json值到运行时值(v)).collect();

            分配数组(vals)

        }

        serde_json::Value::Object(map) => {

            let mut 映射 = Vec::new();

            for (k, v) in map {

                映射.push((堆键::文本(k.clone()), 虚拟机的json值到运行时值(v)));

            }

            分配映射(映射)

        }

    }

}



/// 预留：运行时值 → JSON 转换（解释器侧当前未接线）；显式豁免 dead_code。
#[allow(dead_code)]
fn 虚拟机的运行时值到json值(智值: &运行时值) -> serde_json::Value {

    match 智值.标签 {

        标签_空值 => serde_json::Value::Null,

        标签_逻辑 => serde_json::Value::Bool(智值.整数 != 0),

        标签_整数 => serde_json::json!(智值.整数),

        标签_小数 => serde_json::json!(智值.小数),

        标签_句柄 => match 堆读取(智值.句柄) {

            Some(堆数据::文本(s)) => serde_json::Value::String(s),

            Some(堆数据::文本_静态(p, n)) => {
                let 切片 = unsafe { std::slice::from_raw_parts(p as *const u8, n) };
                serde_json::Value::String(String::from_utf8_lossy(切片).into_owned())
            }

            Some(堆数据::数组(arr)) => serde_json::Value::Array(arr.iter().map(|v| 虚拟机的运行时值到json值(v)).collect()),

            Some(堆数据::映射(map)) => {

                let mut obj = serde_json::Map::new();

                for (k, v) in map {

                    let 键文本 = match k {

                        堆键::整数(i) => i.to_string(),

                        堆键::文本(s) => s.clone(),

                        堆键::逻辑(b) => b.to_string(),

                        // 2026-10-12：新增键变体（与编译器侧 JSON 路径一致）
                        堆键::空值 => "空值".to_string(),

                        堆键::小数(位) => 运行时值::格式化小数显示(f64::from_bits(位)),

                        堆键::结构体 { .. } => 堆键转文本(&k),

                        // 2026-10-12：枚举键 ⇒ `枚举名.成员名`（与编译器侧 JSON 路径、语言渲染一致）
                        堆键::枚举 { .. } => 堆键转文本(&k),

                    };

                    obj.insert(键文本, 虚拟机的运行时值到json值(&v));

                }

                serde_json::Value::Object(obj)

            }

            _ => serde_json::Value::Null,

        },

        _ => serde_json::Value::Null,

    }

}




