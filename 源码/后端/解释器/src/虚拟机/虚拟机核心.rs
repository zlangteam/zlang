    pub fn 调用函数(&mut self, 函数名: &str) -> Result<(), String> {

        let 目标索引 = self.函数表.iter().position(|f| f.名称.contains(函数名));

        if let Some(索引) = 目标索引 {

            let 元数据 = self.函数表[索引].clone();

            let 帧 = 调用帧 { 返回地址: self.代码.len(), 局部变量基址: self.局部变量基址, 操作数栈基址: self.操作数栈.len(), 返回目标寄存器: None };

            self.调用帧栈.push(帧);

            self.局部变量基址 = self.局部变量表.len();

            for _ in 0..元数据.局部变量数量 { self.局部变量表.push(运行时值::空值()); }

            self.指令指针 = 元数据.代码偏移 as usize;

            self.执行();

            Ok(())

        } else { Err(format!("函数【{}】未找到", 函数名)) }

    }



    /// V5: 在"单函数程序"执行态下运行指定函数至完成，返回其结果值。

    /// 由原生任务线程调用：传入函数表索引 `索引` 与参数（本 VM 堆上的 `值`）。

    /// 顶层 返回 的结果经 `主返回值` 捕获并返回。

    pub fn 运行函数(&mut self, 索引: usize, 参数: Vec<运行时值>) -> 运行时值 {

        if 索引 >= self.函数表.len() {

            return 运行时值::空值();

        }

        let meta = self.函数表[索引].clone();

        // 重置为单函数执行态：清空调用帧与任务状态，直接定位函数入口

        self.调用帧栈.clear();

        // ★修复★ 压入"顶层哨兵帧"：入口函数（启动程序）以有顶层帧的方式运行。
        // 否则入口无帧，其调用的子函数返回后帧栈变空，返回指令把 IP 设为子函数调用点续延地址
        // （合法字节码偏移），主循环 while(IP<代码长度) 从程序体中段重跑→续延/副作用重复执行。
        // 顶层帧 返回地址 = 代码长度（终止哨兵），入口返回弹空此帧→主循环退出。
        self.调用帧栈.push(调用帧 {
            返回地址: self.代码.len(),
            局部变量基址: 0,
            操作数栈基址: 0,
            返回目标寄存器: None,
        });

        self.当前任务标识 = 0;

        self.主程序等待 = None;

        self.主程序批量等待 = None;

        self.主程序批量等待超时 = None;

        self.主程序活跃定时器标识 = None;

        let mut 初始局部 = vec![运行时值::空值()];

        for p in 参数 { 初始局部.push(p); }

        let 已分配 = 初始局部.len();

        for _ in 已分配..meta.局部变量数量 as usize { 初始局部.push(运行时值::空值()); }

        self.局部变量表 = 初始局部;

        self.局部变量基址 = 0;

        self.操作数栈.clear();

        self.指令指针 = meta.代码偏移 as usize;

        self.主返回值 = None;

        // 任务可能较长，放宽步数上限（仍保留保护，避免真正死循环卡死线程）

        self.最大步数 = 1_000_000_000;

        self.执行();

        self.主返回值.take().unwrap_or(运行时值::空值())

    }

    /// V5: 同 `运行函数`，但任务结果在堆对象存活时直接深拷贝为自包含 `拥有值`
    /// （避免 `主返回值` 值拷贝后函数栈帧释放导致堆对象悬空、调用方读到空值）。
    /// 用于并发任务返回堆对象（数组/映射/结构体/文本），与编译模式 thunk 打包语义一致。
    pub fn 运行函数到拥有值(&mut self, 索引: usize, 参数: Vec<运行时值>) -> 拥有值 {
        if 索引 >= self.函数表.len() {
            return 拥有值::空值;
        }
        let meta = self.函数表[索引].clone();
        // 本入口是任务/HTTP 处理器在后台线程上的「顶层」执行起点：先清除本线程残留的 base 异常状态。
        // 「待处理」标志是线程局部的，上一次执行若以未捕获异常结束，标志会留在线程上；
        // 各转发点只在「调用前待处理 == 0」时才把 base 异常转成虚拟机异常，
        // 于是同一线程上之后的越界、除零等异常会被静默吞掉（HTTP 服务线程会被反复复用）。
        base::异常运行时::智语言_清除当前异常();
        base::异常运行时::智语言_复位待重抛();
        // 重置为单函数执行态：清空调用帧与任务状态，直接定位函数入口
        self.调用帧栈.clear();
        self.当前任务标识 = 0;
        self.主程序等待 = None;
        self.主程序批量等待 = None;
        self.主程序批量等待超时 = None;
        self.主程序活跃定时器标识 = None;
        let mut 初始局部 = vec![运行时值::空值()];
        for p in 参数 { 初始局部.push(p); }
        let 已分配 = 初始局部.len();
        for _ in 已分配..meta.局部变量数量 as usize { 初始局部.push(运行时值::空值()); }
        self.局部变量表 = 初始局部;
        self.局部变量基址 = 0;
        self.操作数栈.clear();
        self.指令指针 = meta.代码偏移 as usize;
        self.主返回拥有值 = None;
        // 任务不设步数上限：与编译模式一致（编译产物没有步数概念）。旧的 10 亿步上限会让
        // 常驻 worker / 服务循环在解释模式下运行一段时间后被强制终止，且异常被抑制、完全静默。
        self.最大步数 = u64::MAX;
        self.执行();
        self.主返回拥有值.take().unwrap_or(拥有值::空值)
    }



