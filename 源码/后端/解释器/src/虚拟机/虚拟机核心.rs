    fn 处理调用寄存器(&mut self) {

        let 函数索引 = self.读u16() as usize;

        let 参数个数 = self.代码[self.指令指针]; self.指令指针 += 1;

        let dest = self.解析操作数();



        let mut 参数列表: Vec<运行时值> = Vec::with_capacity(参数个数 as usize);

        for _ in 0..参数个数 {

            参数列表.push(self.读带标记操作数());

        }



        if 函数索引 < 8 {

            let 参数 = 参数列表.first().cloned().unwrap_or(运行时值::空值());

            // ⚡双模式⚡ A5 异常传播守卫：仅当「调用前 待处理=0 且 调用后=1」时本调用才真正抛出。
            //   进入 finally（re-throw 动态路由）时 待处理 被契约故意保留为 1（供 finally 末尾条件跳转
            //   判定重抛）；此时 finally 体内任何系统函数调用若按「待处理==1 即抛」会误判为异常而截断 finally
            //   体（实测 组合戊 / 丙 复现）。正常 catch 入口已 清除待处理(=0)，故过渡语义与此前完全一致。
            let 调用前待处理 = base::异常运行时::智语言_异常待处理();

            let result = match 函数索引 {

                0 => {
                    if !参数列表.is_empty() && 参数.标签 == 标签_空值 {
                        // ⚡双模式⚡ 对齐规范 §1518/§3298：输出(空值) 空值不参与类型转换（解释模式内联路径，与 base 索引0 一致）
                        let 消息 = "空值不能参与类型转换".to_string();
                        base::异常运行时::智语言_抛出异常(
                            "类型转换错误".as_ptr(), "类型转换错误".len() as i64,
                            消息.as_ptr(), 消息.len() as i64);
                        // 异常已抛出：跳过输出，返回空值作为分支值（分发层将检测异常待处理并跳转 catch）
                        运行时值::空值()
                    } else {
                        let 文本 = self.值转文本(&参数);
                        if self.捕获输出 {
                            self.输出缓冲.push(文本);
                        } else {
                            println!("{}", 文本);
                        }
                        运行时值::空值()
                    }
                }

                1 => base::系统调用(1, &参数列表),

                2 => base::系统调用(2, &参数列表),

                3 => { self.分发系统函数寄存器(3, &参数列表) } // A1: 输入() 委托运行时统一系统调用（编译模式已通，双模式一致）

                4 => { let s = base::值类型::运行时值取类型名称(&参数); let id = 堆分配(堆数据::文本(s)); 运行时值::句柄(id) }

                5 => base::异常运行时::智语言_构造异常错误结构体(),

                6 => base::系统调用(6, &参数列表),

                7 => base::系统调用(7, &参数列表),

                _ => 运行时值::空值(),

            };

            // ⚡双模式⚡ A5: 内联核心系统函数（如 整数() 文本解析失败）经线程局部异常标志抛出。

            //   此处桥接到 VM 触发异常（与除零/越界同源），运行循环将跳转 catch。

            if 调用前待处理 == 0 && base::异常运行时::智语言_异常待处理() == 1 {

                if let Some(载荷) = base::异常运行时::取当前异常() {

                    base::异常运行时::智语言_清除当前异常();

                    self.触发异常(&载荷.类型, 载荷.描述);

                    return;

                }

            }

            self.写结果(&dest, result);

        } else if 函数索引 < frontend::底层表示::模块结构::用户函数索引基址 {

            // ── V3: 系统函数计入步数（0..用户函数索引基址 为系统函数空间）──

            self.执行步数 += 50; // 系统调用相当于50条普通指令



            let 调用前待处理 = base::异常运行时::智语言_异常待处理();

            let result = self.分发系统函数寄存器(函数索引, &参数列表);



            // ⚡双模式⚡ A5: 系统函数（单源）可能经线程局部标志抛出运行时异常。

            //   编译模式由代码生成在 CALL 后注入检查捕获；解释模式在此桥接——

            //   若系统函数已置异常待处理，则转发给 VM 的 触发异常（与除零/越界同源），并跳过结果写回。

            if 调用前待处理 == 0 && base::异常运行时::智语言_异常待处理() == 1 {

                if let Some(载荷) = base::异常运行时::取当前异常() {

                    base::异常运行时::智语言_清除当前异常();

                    self.触发异常(&载荷.类型, 载荷.描述);

                    return;

                }

            }



            // 高开销系统函数额外计步

            match 函数索引 {

                28 => { /* 休眠不计额外步数 */ }

                40 | 41 => { self.执行步数 += 100; } // 网络调用

                98 => { self.执行步数 += 100; }      // 多路监听

                _ => {}

            }



            self.写结果(&dest, result);

            } else if 函数索引 >= frontend::底层表示::模块结构::用户函数索引基址 && 函数索引 < 65535 {

                let func_idx = 函数索引 - frontend::底层表示::模块结构::用户函数索引基址;

                if func_idx < self.函数表.len() {

                    let meta = self.函数表[func_idx].clone();

                let 返回目标 = if let 操作数源::寄存器(idx) = dest { Some(idx) } else { None };

                // ── 失控递归防护：调用帧栈深度超上限抛「栈溢出」异常（可被 捕获 捕获）──
                // 走 触发异常 标准入口（而非手动置位）：它同步写 base 线程局部载荷、
                // 构造堆栈并置待处理，由主循环统一派发——手动置位会留下不一致的派发状态，
                // 导致捕获后末尾语句被重复执行（与编译模式输出分叉）。
                if self.调用帧栈.len() >= self.最大调用深度 {
                    self.触发异常("栈溢出", format!("函数调用递归深度超过上限({})，可能存在失控递归", self.最大调用深度));
                    return;
                }

                let frame = 调用帧 { 返回地址: self.指令指针, 局部变量基址: self.局部变量基址, 操作数栈基址: self.操作数栈.len(), 返回目标寄存器: 返回目标 };

                self.调用帧栈.push(frame);

                self.局部变量基址 = self.局部变量表.len();

                self.局部变量表.push(运行时值::空值());



            // ── 统一架构：参数传递——运行时值直接入栈，GC自动管理引用 ──

            for arg in 参数列表 {

                self.局部变量表.push(arg);

            }

                let 已分配 = 1 + meta.参数数量 as usize;

                for _ in 已分配..meta.局部变量数量 as usize {

                    self.局部变量表.push(运行时值::空值());

                }

                self.指令指针 = meta.代码偏移 as usize;

            } else {

                eprintln!("[VM警告] 调用未定义的函数(索引{}), 返回空值", 函数索引);

                self.写结果(&dest, 运行时值::空值());

            }

           }

    }


