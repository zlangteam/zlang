/// 定时器条目 — 存入最小堆，按截止步数排序

/// 使用 Reverse 包装，使 BinaryHeap 成为最小堆

#[derive(Debug, Clone, PartialEq, Eq)]

pub(crate) struct 定时器条目 {

    pub(crate) 截止步数: u64,        // 绝对步数值（定时器触发时的执行步数）

    pub(crate) 任务标识: usize,       // 到期时应唤醒的任务

    pub(crate) 定时器标识: u64,       // 唯一ID，用于惰性取消

}



impl Ord for 定时器条目 {

    fn cmp(&self, other: &Self) -> std::cmp::Ordering {

        self.截止步数.cmp(&other.截止步数)

            .then_with(|| self.定时器标识.cmp(&other.定时器标识))

    }

}



impl PartialOrd for 定时器条目 {

    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {

        Some(self.cmp(other))

    }

}





