// ============================================================
// 【缺口 C 修复：FFI 回调打通 — 解释器侧用户函数调用器桥】
// shim trampoline 经 智语言_系统调用回调 → base 执行用户函数回调 → 调用本桥。
// 本桥把裸指针还原为 &mut 虚拟机核心，调用已有的可重入入口 调用函数带参数。
// FFI 回调是同线程同步重入（发生在 处理外部调用 持有的 &mut VM 上下文内），
// 故用裸指针 + unsafe 受控还原是安全的（VM 实例在 C 回调返回前始终有效）。
// ============================================================

/// 解释器用户函数调用器桥：第一参数 = VM 指针地址(usize)；第二 = 用户函数索引(≥200)；
/// 第三 = 实参裸指针；第四 = 实参长度；第五 = 结果写回指针（32 字节 运行时值）。
/// 普通 fn 指针（注册点要求 Sync）。结果经输出指针回写（与编译模式 thunk 统一约定）。
extern "C" fn 解释器回调桥(
    vm_ptr: usize,
    索引: usize,
    参数指针: *const base::值类型::运行时值,
    参数数量: usize,
    输出: *mut base::值类型::运行时值,
) {
    if vm_ptr == 0 || 输出.is_null() {
        return;
    }
    let 参数: Vec<base::值类型::运行时值> = if 参数指针.is_null() {
        Vec::new()
    } else {
        unsafe { std::slice::from_raw_parts(参数指针, 参数数量).to_vec() }
    };
    let vm = unsafe { &mut *(vm_ptr as *mut 虚拟机) };
    let 结果 = vm.调用函数带参数(索引, &参数);
    unsafe { *输出 = 结果; }
}

/// RAII 守卫：进入 执行 时注册回调桥，任何 return/异常路径均自动恢复「进入前的注册项」。
/// 必须恢复而非清空：`执行()` 会被 FFI 回调经 `调用函数带参数` 嵌套重入，
/// 内层守卫若直接注销，外层仍在进行的外部调用后续回调将全部失效（静默返回空值）。
/// 最外层守卫进入前注册表为空，恢复即等价于注销，不留悬垂指针。
struct 回调桥守卫 {
    先前注册: Option<(base::外部调用注册::用户函数调用器, usize)>,
}
impl 回调桥守卫 {
    fn 启用(vm_ptr: usize) -> 回调桥守卫 {
        let 先前注册 = base::外部调用注册::替换用户函数调用器(Some((解释器回调桥, vm_ptr)));
        回调桥守卫 { 先前注册 }
    }
}
impl Drop for 回调桥守卫 {
    fn drop(&mut self) {
        base::外部调用注册::替换用户函数调用器(self.先前注册.take());
    }
}

// ═══════════════════════════════════════════════════════
//  HTTP 服务端后台执行器桥（2026-08-19 阶段二统一）
//  与 解释器回调桥 的差异：回调桥是「同线程重入主 VM」（仅 FFI 回调安全）；
//  本桥是「跨线程新建子 VM」——HTTP 服务端在后台 accept 线程同步调用处理器时，
//  主 VM 可能正阻塞于网络获取/TCP 读等调用，绝不能重入。故每次调用新建独立子 VM
//  执行目标函数（与 并发执行器 的任务子 VM 同款），字节码经 Arc 上下文传入。
//  注册点由 后台执行器守卫 持有 Arc 保活（VM 存活期间指针恒有效）。
// ═══════════════════════════════════════════════════════
extern "C" fn 后台解释器执行器(
    上下文: usize,
    索引: usize,
    参数指针: *const base::值类型::运行时值,
    参数数量: usize,
    输出: *mut base::值类型::运行时值,
) {
    if 上下文 == 0 || 输出.is_null() {
        return;
    }
    // 上下文 = 守卫持有的 Arc<Vec<u8>> 内部 Vec 的地址（Arc::as_ptr 返回 *const Vec<u8>），
    // 守卫持有 Arc 保证 ArcInner 存活；此处还原为 &Vec<u8>（勿 reinterpret 为 Arc 结构，布局不同）。
    let 字节码: &Vec<u8> = unsafe { &*(上下文 as *const Vec<u8>) };
    let 参数: Vec<base::值类型::运行时值> = if 参数指针.is_null() {
        Vec::new()
    } else {
        unsafe { std::slice::from_raw_parts(参数指针, 参数数量).to_vec() }
    };
    // 解码用户函数索引（用户函数索引基址+i 约定 → 运行时函数表索引），与 并发执行器 一致
    let fi = if 索引 >= frontend::底层表示::模块结构::用户函数索引基址 { 索引 - frontend::底层表示::模块结构::用户函数索引基址 } else { 索引 };
    let mut 子虚拟机 = 虚拟机::新建();
    子虚拟机.加载字节码(字节码);
    let 结果 = 子虚拟机.运行函数到拥有值(fi, 参数);
    let 结果运行时 = if 子虚拟机.异常激活 {
        // 处理器抛异常 → 回空值（HTTP 提取响应字段 对非句柄返回 500 默认响应）
        base::值类型::运行时值::空值()
    } else {
        子虚拟机.拥有值到运行时值(&结果)
    };
    unsafe { *输出 = 结果运行时; }
}

/// RAII 守卫：注册后台解释器执行器（上下文 = 字节码 Arc 指针），任何 return/异常路径自动注销。
/// 计数防嵌套：`执行()` 可能被 `调用函数带参数` 嵌套调用（内部函数调用再调 执行()），
/// 只有最外层守卫才注册/注销，避免内层 return 把注册表清空导致 HTTP 后台线程回退到
/// 非线程安全的 解释器回调桥（跨线程重入主 VM）。
struct 后台执行器守卫 {
    _字节码: std::sync::Arc<Vec<u8>>,
}
impl 后台执行器守卫 {
    fn 启用(原始字节码: &Vec<u8>) -> 后台执行器守卫 {
        let 字节码 = std::sync::Arc::new(原始字节码.clone());
        let 上下文 = std::sync::Arc::as_ptr(&字节码) as usize;
        if 后台执行器活跃计数.fetch_add(1, std::sync::atomic::Ordering::SeqCst) == 0 {
            base::外部调用注册::注册后台用户函数执行器(后台解释器执行器, 上下文);
        }
        后台执行器守卫 { _字节码: 字节码 }
    }
}
impl Drop for 后台执行器守卫 {
    fn drop(&mut self) {
        if 后台执行器活跃计数.fetch_sub(1, std::sync::atomic::Ordering::SeqCst) == 1 {
            base::外部调用注册::注销后台用户函数执行器();
        }
    }
}

/// 后台执行器注册嵌套计数（0=未注册，>0=有活跃守卫，最外层守卫负责注册/注销）。
static 后台执行器活跃计数: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);



