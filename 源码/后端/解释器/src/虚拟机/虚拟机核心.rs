    fn 执行间接加载寄存器(&mut self) {

        let _count = self.代码[self.指令指针]; self.指令指针 += 1;

        let dest = self.解析操作数();

        let src = self.读带标记操作数();

        let result = if src.标签 == 标签_局部引用 {

            self.局部变量表.get(src.整数 as usize).cloned().unwrap_or(运行时值::空值())

        } else {

            src

        };

        self.写结果(&dest, result);

    }



    fn 执行间接存储寄存器(&mut self) {

        let _count = self.代码[self.指令指针]; self.指令指针 += 1;

        let dest_ref = self.解析操作数(); // 局部引用目标

        let val = self.读带标记操作数();  // 新值

        let ref_idx = match &dest_ref {

            操作数源::寄存器(idx) => self.局部变量表.get(*idx).and_then(|v| {

                if v.标签 == 标签_局部引用 { Some(v.整数 as usize) } else { None }

            }),

            _ => None,

        };

        if let Some(idx) = ref_idx {

            // 统一架构：GC 管理引用计数，无需手动释放/增加

            while self.局部变量表.len() <= idx { self.局部变量表.push(运行时值::空值()); }

            self.局部变量表[idx] = val;

        }

    }



