    fn 处理创建闭包寄存器(&mut self) {

        // 编码: 0xE2 func_idx(u16) capture_count(u8) dest(operand) capt1(operand)...captN(operand)

        let 函数索引 = self.读u16() as usize;

        let 捕获数量 = self.代码[self.指令指针]; self.指令指针 += 1;

        let dest = self.解析操作数();



        let mut 捕获变量 = Vec::with_capacity(捕获数量 as usize);

        for _ in 0..捕获数量 {

            捕获变量.push(self.读带标记操作数());

        }



        // 🆕 2026-09-22 引用计数闭环（**+1 侧**）：捕获句柄逐个 +1，
        //   与 `值类型.rs::分配闭包` 同约定（该函数同样对捕获句柄 `堆增加引用`）。
        //   此前 VM 侧直接 `堆分配` 而未对捕获句柄 +1 ⇒ 闭包环境级联 −1（`收集子句柄` 的 `闭包环境` 分支）
        //   属「无中生有」⇒ **欠计数**（长期泄漏 + 误回收风险）。
        // ✅ 2026-09-22 启用（P1 解禁）：原"暂缓"理由（「超时后句柄仍有效」等 2 例解释模式失败）经
        //   **唯一变量法**证实是 **F4 = 本批引入的回归（已修复）**，与本项无关 ⇒ 现予启用，恢复两引擎同源。
        //   不变量：闭包环境**持有**每个捕获句柄一份引用 ⇒ 与 `收集子句柄` 的 `闭包环境` 分支 −1 **严格对称** ✓
        for 捕获 in 捕获变量.iter() {
            if 捕获.标签 == 标签_句柄 && 捕获.句柄 != 0 { base::值类型::堆增加引用(捕获.句柄); }
        }
        let id = 堆分配(堆数据::闭包环境 { 函数索引, 捕获变量 });

        self.写结果(&dest, 运行时值::句柄(id));

    }



    fn 处理间接调用寄存器(&mut self) {

        // 编码: 0xE1 arg_count(u8) dest(operand) closure_src(operand) arg1...argN

        let 参数个数 = self.代码[self.指令指针]; self.指令指针 += 1;

        let dest = self.解析操作数();

        let closure_src = self.读带标记操作数();



        let mut 参数列表: Vec<运行时值> = Vec::with_capacity(参数个数 as usize);

        for _ in 0..参数个数 {

            参数列表.push(self.读带标记操作数());

        }



        // 从闭包值中提取函数索引和捕获变量

        // 统一架构：闭包环境在运行时全局堆

        let (func_idx, 捕获变量) = if closure_src.标签 == 标签_句柄 {

            match 堆读取(closure_src.句柄) {

                Some(堆数据::闭包环境 { 函数索引, 捕获变量 }) => (函数索引, 捕获变量),

                _ => { self.写结果(&dest, 运行时值::空值()); return; }

            }

        } else if closure_src.标签 == 标签_函数指针 {

            // ⚡双模式⚡ 函数指针值采用负编码（整数 = -(函数索引)-1），须经 取函数索引() 还原真实索引
            (closure_src.取函数索引().unwrap_or(0), vec![])

        } else {

            self.写结果(&dest, 运行时值::空值());

            return;

        };



        // 合并捕获变量和参数：捕获变量在前，实际参数在后

        let mut 完整参数 = 捕获变量;

        完整参数.extend(参数列表);



        // ⚡双模式⚡ 函数引用索引归一：普通函数引用为 0 基真实索引；
        // 并发任务 thunk 等场景以 200 偏移发出，此处统一归一（与并发执行器一致）。
        let fi = if func_idx >= frontend::底层表示::模块结构::用户函数索引基址 && func_idx < 65535 { func_idx - frontend::底层表示::模块结构::用户函数索引基址 } else { func_idx };

        if fi < self.函数表.len() {

                let meta = self.函数表[fi].clone();

                let 返回目标 = if let 操作数源::寄存器(idx) = dest { Some(idx) } else { None };

                // ── 失控递归防护：调用帧栈深度超上限抛「栈溢出」异常（可被 捕获 捕获）──
                // 走 触发异常 标准入口（而非手动置位）：它同步写 base 线程局部载荷、
                // 构造堆栈并置待处理，由主循环统一派发——手动置位会留下不一致的派发状态，
                // 导致捕获后末尾语句被重复执行（与编译模式输出分叉）。
                if self.调用帧栈.len() >= self.最大调用深度 {
                    self.触发异常("栈溢出", format!("函数调用递归深度超过上限({})，可能存在失控递归", self.最大调用深度));
                    return;
                }

                let frame = 调用帧 { 返回地址: self.指令指针, 局部变量基址: self.局部变量基址, 操作数栈基址: self.操作数栈.len(), 返回目标寄存器: 返回目标 };

                self.调用帧栈.push(frame);

                self.局部变量基址 = self.局部变量表.len();

                self.局部变量表.push(运行时值::空值());

                for arg in 完整参数 { self.局部变量表.push(arg); }

                let 已分配 = 1 + meta.参数数量 as usize;

                for _ in 已分配..meta.局部变量数量 as usize { self.局部变量表.push(运行时值::空值()); }

                self.指令指针 = meta.代码偏移 as usize;

                return;

            }

        self.写结果(&dest, 运行时值::空值());

    }





