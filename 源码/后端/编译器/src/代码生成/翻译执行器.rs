                self.存储值对(构建器, &指令.操作数1, 源标签, 源载荷);
                // ⚡双模式⚡ 变量重定型：store 后把目标局部变量槽的静态类型标志刷新为源值类型，
                // 与算术结果回写（记录结果类型，见 操作数执行器.rs:213）同一机制、同一张表，
