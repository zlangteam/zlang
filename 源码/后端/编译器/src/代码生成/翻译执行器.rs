                // 必须从源(操作数2)读取 (标签,载荷) 并写回目标(操作数1)，
                // 否则变量赋值永远写不进目标（此前导致 a=[] 等赋值结果为空值）。
                let 源操作数 = 指令.操作数2.as_ref().unwrap_or(&指令.操作数1);
