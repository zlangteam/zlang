/// 标准库条目种类 —— 决定「是否可裸调」「是否入函数式调用禁用黑名单」等派生行为
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum 标准库种类 {
    /// 模块公开函数（须 模块.函数 限定调用，导入后）：数学.绝对值、文件.读取 等
    模块公开函数,
    /// 全局函数（裸调合法，§4.1 共 8）：输出/输入/错误输出/转整数/转小数/转文本/类型/异常错误
    全局函数,
    /// 容器方法（映射/数组/通用容器）—— 自动进入「函数式调用禁用」黑名单
    容器方法,
    /// 文本方法
    文本方法,
    /// 数学内建类型方法（精确小数/短小数/无符号整数/字节/无限整数）
    数学内建方法,
    /// 类型转换函数（部分有专用 opcode）
    转换函数,
    /// 并发函数
    并发函数,
    /// 句柄方法（网络连接/网络响应/通道/任务/终止器 等不透明运行时句柄）
    句柄方法,
    /// 编译器合成/内部名（不可直接裸调，仅编译器合成或方法分派触达）
    内部名,
}

/// 操作码选择器 —— 标准库函数降级为 LIR 时的执行方式
///   走调用: 无专用 opcode，走 操作码::调用（按 索引 分派到 base）
///   固定:   名→opcode 一对一（绝大多数容器/文本/转换函数）
///   按元数: 依实参个数选择（如 并发.批量等待 1参→批量等待 / 2参→批量等待超时）
// 注：操作码 枚举未实现 Copy（仅 Clone），故本选择器也只 Clone。
#[derive(Clone, Debug)]
pub enum 操作码选择器 {
    走调用,
    固定(操作码),
    按元数(&'static [(usize, 操作码)]),
}

impl 操作码选择器 {
    /// 依实参个数解析最终操作码（None = 走 CALL）
    pub fn 取操作码(&self, 实参个数: usize) -> Option<操作码> {
        match self {
            操作码选择器::走调用 => None,
            操作码选择器::固定(码) => Some(码.clone()),
            操作码选择器::按元数(表) => 表
                .iter()
                .filter(|(元数, _)| *元数 <= 实参个数)
                .max_by_key(|(元数, _)| *元数)
                .map(|(_, 码)| 码.clone()),
        }
    }
}

