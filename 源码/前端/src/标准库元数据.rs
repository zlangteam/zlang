/// 派生：全局函数（§4.1 预定义标识符）的返回类型文本。
/// 单一真相：标准库注册表 中 种类 = 全局函数 条目的 返回 字段。
/// None = 该全局函数无返回值（输出/错误输出）或不是全局函数。
/// ★取代 表达式分析.rs 手写的「内置函数返回类型」match★（旧 match 因改名失效）。
pub fn 全局函数返回类型(名: &str) -> Option<&'static str> {
    标准库注册表
        .iter()
        .find(|e| e.种类 == 标准库种类::全局函数 && e.函数名 == 名)
        .and_then(|e| e.返回)
}

/// 派生：全局函数的返回类型文本（无返回值者按「空值」处理）。
/// 返回 None 表示「该名字不是全局函数」（调用方应回退到用户函数签名查询）。
pub fn 全局函数返回类型_或空值(名: &str) -> Option<&'static str> {
    if 全局函数名集合().contains(名) {
        Some(全局函数返回类型(名).unwrap_or("空值"))
    } else {
        None
    }
}

/// 派生：全局函数（§4.1）允许的实参个数区间 `(最少, 最多)`。
///
/// ★单源★：来自 标准库注册表 中 种类 = 全局函数 条目的 `形参` 长度；`异常错误` 是
///   构造特例（0 参 = 取当前异常 / 1 参 = 由消息构造），故单独登记为 `(0, 1)`。
///
/// 返回 None 表示「该名字不是全局函数」（内含 `创建数组`/`创建映射` 等编译器内部名 → 不校验）。
///
/// 背景（2026-10-19）：此前全局函数无论是否登记形参都**完全跳过**参数校验，实测
///   `转整数()` 静默返回 0、`转文本()` 静默返回 `"空值"`、`输出("甲","乙")` 静默丢弃第二个实参。
///   这类「静默接受错误调用」与规范「签名即契约」冲突，故在语义层按本函数做编译期拦截。
/// ⚡双模式⚡ 纯静态判定，两模式共用同一前端 ⇒ 天然 parity。
pub fn 全局函数参数个数区间(名: &str) -> Option<(usize, Option<usize>)> {
    if 名 == "异常错误" {
        return Some((0, Some(1)));
    }
    标准库注册表
        .iter()
        .find(|e| e.种类 == 标准库种类::全局函数 && e.函数名 == 名)
        .map(|e| (e.形参.len(), Some(e.形参.len())))
}

/// 启动自检：标准库索引一致性。
/// 运行期可安全断言的不变量（不会误伤合法情形）：
///   ① 索引越界：系统函数索引必须 < 用户函数索引基址（用户函数从 用户函数索引基址 起），违者即索引空间错位。
///   ② 同名重载一致：同一 规范全名 若多次登记，索引必须一致（如 数学.最大值(甲,乙) 与 数学.最大值(列表)
///      均指向 数学_最大值），否则即重载分派错位。
///   ③ 方法分派合成全名命中：点号方法条目（精确小数.加法 / 通道.发送 等）的前缀经 方法分派模块 派发的
///      模块必须等于条目实际归属模块——否则调用点按「模块.方法」合成的规范全名落空或错位
///      （历史回归：双重前缀 "任务.任务.等待结果"），首次查表即报红。
/// 关于「不同名共享索引」：本表刻意保留别名层（如 网络.连接读取 / 网络连接.读取 / 系统网络连接读取
///   共用同一 base 索引），仅靠数值索引无法与「真实冲突」区分，故不在运行期断言。真正的索引唯一性
///   保证来自「元数据表 与 base 的 match 臂共用 标准库索引::X 常量」——同一常量绝不会在两处被赋不同
///   数值，编译期即固化为单源。
/// 双模式统一：解释/编译两模式首次查表即触发，fail-fast 暴露索引双源遗漏。
pub fn 自检_索引一致() {
    let mut 全名索引: HashMap<String, usize> = HashMap::new();
    for 条目 in 标准库注册表.iter() {
        if 条目.索引 == usize::MAX {
            continue; // 纯 opcode 型（无 CALL 索引）跳过
        }
        if 条目.索引 >= crate::底层表示::模块结构::用户函数索引基址 {
            panic!(
                "[标准库自检] 索引 {} ({}) 越界：系统函数索引必须低于 用户函数索引基址",
                条目.索引, 条目.规范全名()
            );
        }
        // ② 同名重载一致性
        if let Some(&已登记索引) = 全名索引.get(&条目.规范全名()) {
            if 已登记索引 != 条目.索引 {
                panic!(
                    "[标准库自检] 同名 {} 索引不一致：{} 与 {}",
                    条目.规范全名(), 已登记索引, 条目.索引
                );
            }
        } else {
            全名索引.insert(条目.规范全名(), 条目.索引);
        }
    }
    // ③ 方法分派合成全名命中：点号方法条目的前缀经 方法分派模块 派发模块须等于条目所属模块。
    for 条目 in 标准库注册表.iter() {
        if !条目.函数名.contains('.') || 条目.模块.is_empty() {
            continue;
        }
        let 前缀 = &条目.函数名[..条目.函数名.find('.').unwrap()];
        let 派发模块 = 方法分派模块(前缀);
        if 派发模块 != 条目.模块 {
            panic!(
                "[标准库自检] 方法分派歧义：前缀『{}』归属模块『{}』，但 方法分派模块 派发到『{}』（条目 {}）",
                前缀, 条目.模块, 派发模块, 条目.规范全名()
            );
        }
    }
}

/// 派生：函数式容器调用禁用黑名单（替代 表达式分析.rs 手工维护列表）。
/// 规则：种类=容器方法（含字面量构造 创建数组/创建映射）一律须用
///       对象.方法() 或 []/{} 语法，禁止函数式调用；新增容器方法自动纳入，无需手工维护。
static 派生禁用名单: OnceLock<std::collections::HashSet<String>> = OnceLock::new();

pub fn 函数式调用禁用名单() -> &'static std::collections::HashSet<String> {
    派生禁用名单.get_or_init(|| {
        标准库注册表
            .iter()
            .filter(|e| e.种类 == 标准库种类::容器方法)
            .flat_map(|e| {
                let mut 名列表 = vec![e.函数名.to_string()];
                if let Some(b) = e.base名 {
                    名列表.push(b.to_string());
                }
                名列表
            })
            .collect()
    })
}

