/// 唯一例外：精确小数 的方法在注册表归属 "数学" 模块（与 短小数/无符号整数 对称），
/// 派生：方法分派模块（替代 语句转换.rs:1278 硬编码 "精确小数"→"数学"）。
/// 单源：结构体方法所属模块直接由注册表派生（与 标准库条目.模块 一致），
/// 不再对 任务/通道/网络连接 等返回「自身名」导致合成分派名双重前缀
/// （如 "任务.任务.等待结果"，破坏 零开销发射 判定与 CALL 索引解析）。
/// 精确小数 经此自然落到 "数学"；短小数等 5 类数学内建同归 "数学"；
/// 任务/通道/终止器 归 "并发"；网络连接系 归 "网络"。
pub fn 方法分派模块(结构体名: &str) -> &str {
    标准库注册表
        .iter()
        .find(|e| {
            e.函数名.len() > 结构体名.len()
                && e.函数名.starts_with(结构体名)
                && e.函数名.as_bytes()[结构体名.len()] == b'.'
        })
        .map(|e| e.模块)
        .unwrap_or(结构体名)
}

