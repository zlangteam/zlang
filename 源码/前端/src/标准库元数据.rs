/// 派生：按模块分组（保持注册表原始顺序，模块名去重）
/// 供语义层 预注册内置模块符号 注入符号表使用，取代函数内手写嵌套表。
pub fn 按模块分组() -> Vec<(&'static str, Vec<&'static 标准库条目>)> {
    let mut 模块顺序: Vec<&'static str> = Vec::new();
    for 条目 in 标准库注册表 {
        // 仅「模块公开函数 / 并发函数」注入符号表（对应原 内置模块 表的 7 个模块）。
        // 数学内建方法 / 句柄方法 / 内部名 属编译器内部，不注入（否则会被用户裸调，破坏可见性设计）。
        let 需注入 = 条目.种类 == 标准库种类::模块公开函数 || 条目.种类 == 标准库种类::并发函数;
        if 需注入 && !条目.模块.is_empty() && !模块顺序.contains(&条目.模块) {
            模块顺序.push(条目.模块);
        }
    }
    模块顺序
        .into_iter()
        .map(|m| (m, 标准库注册表.iter().filter(|e| e.模块 == m).collect()))
        .collect()
}

/// 派生：规范全名 → 索引（跳过 usize::MAX 的专用 opcode 型）
static 派生索引映射: OnceLock<HashMap<String, usize>> = OnceLock::new();

/// 派生：规范全名 → 索引（跳过 usize::MAX 的专用 opcode 型）。
/// 同时注入 base名（如 句柄方法 "通道.发送" / 系统内部名 "系统网络获取"），
/// 使本映射完整覆盖旧 公共降级.rs::内置索引 的全部多态命名空间 key，
/// 从而可彻底删除内置索引（2026-08-30 单源收尾）。
pub fn 取标准库索引映射() -> &'static HashMap<String, usize> {
    派生索引映射.get_or_init(|| {
        自检_索引一致(); // 双模式统一：首次查表即触发，fail-fast 暴露索引双源遗漏
        let mut 映射 = HashMap::new();
        for 条目 in 标准库注册表 {
            if 条目.索引 != usize::MAX {
                映射.insert(条目.规范全名(), 条目.索引);
                if let Some(b) = 条目.base名 {
                    映射.insert(b.to_string(), 条目.索引);
                }
                // 异常错误.格式信息()：方法调用通用路径按 结构体名.方法名 拼为 "异常错误.格式信息"，
                // 内部名规范化名为 "异常错误格式信息"。两者并存注册，确保两种写法都能解析到同一索引（双模式一致）。
                if 条目.是异常错误格式方法 {
                    映射.insert("异常错误.格式信息".to_string(), 条目.索引);
                    映射.insert("异常错误.异常错误.格式信息".to_string(), 条目.索引);
                }
            }
        }
        映射
    })
}

